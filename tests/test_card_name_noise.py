"""Имя товара из карточки витрины: чистка наклеек и цены.

ЗАМЕР 20.10.2026 (боевая база). У Пятёрочки 26 строк остались без единого товара — не
сопоставились, потому что имя пришло с витрины ВМЕСТЕ с тем, что вокруг товара:
«-22% 4,95 Томатная паста Помидорка 250мл 250 мл 205 00 ₽», «Комбо 4,88 Суп-пюре грибной
Пятёрочка Кафе 250г», «Нет оценок Мороженое Snickers…». Сопоставление по такому имени
товар не находит, и строка выпадает из сравнения сетей.

Те же строки важны именно у телефонных сетей: Пятёрочке и Самокату каталог приносит
телефон, и другого источника имени у них нет. Поэтому чистка — не косметика, а условие
того, что их товары попадут в сопоставление.

Строки ниже — не выдумка: это настоящие имена из базы, снятые 20.10.2026. Они остались
от 18.10, когда чистки ещё не было; починить их пришлось разово (25 из 26), а этот тест
держит саму чистку: если она перестанет снимать наклейку или хвост с ценой, строки снова
начнут выпадать.
"""
from __future__ import annotations

import os
import sys

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from app.phonecart import _card_name  # noqa: E402

# Настоящие имена из боевой базы 20.10.2026 (первые 60 символов) и то, что от них осталось.
REAL = [
    ("Сыр Galbani Маскарпоне 80% БЗМЖ 250г 250 г 629 00 ₽",
     "Сыр Galbani Маскарпоне 80% БЗМЖ 250г 250 г"),
    ("Комбо 4,84 Суп гороховый с копченостями Пятёрочка Кафе 250г",
     "Суп гороховый с копченостями Пятёрочка Кафе 250г"),
    ("-22% 4,95 Томатная паста Помидорка 250мл 250 мл 205 00 ₽",
     "Томатная паста Помидорка 250мл 250 мл"),
    ("-30% 4,86 Манго спелое Египет Цена за 1 кг 389 99 ₽",
     "Манго спелое Египет Цена за 1 кг"),
    ("-13% 4,93 Туалетная бумага Tolli Lux белая 3 слоя 8шт. 8 шт 164 99 ₽",
     "Туалетная бумага Tolli Lux белая 3 слоя 8шт. 8 шт"),
    ("Нет оценок Мороженое Snickers сливочное с пастой из арахиса, 90 г",
     "Мороженое Snickers сливочное с пастой из арахиса, 90 г"),
    ("-28% Нет оценок Чистящее средство Shima Home Strong Bathroom Cleaner 500 мл",
     "Чистящее средство Shima Home Strong Bathroom Cleaner 500 мл"),
    ("Сосиски Клинский МК Венские варёные, 410г 410 г 399 99 ₽",
     "Сосиски Клинский МК Венские варёные, 410г 410 г"),
]


@pytest.mark.parametrize("raw, clean", REAL)
def test_a_showcase_name_loses_its_badge_and_price(raw, clean):
    assert _card_name(raw) == clean


def test_no_money_is_left_in_a_clean_name():
    """В имени товара не должно оставаться ни наклейки, ни цены — по ним не сопоставить."""
    for raw, _ in REAL:
        clean = _card_name(raw)
        assert "₽" not in clean, clean
        assert not clean.startswith("-"), clean
        assert "Комбо " not in clean and "Нет оценок" not in clean, clean
        assert not clean.endswith(" 00"), clean
