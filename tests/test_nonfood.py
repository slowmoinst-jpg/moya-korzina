"""Распознаватель непродуктовых строк: услуги, доставка, платежи, аренда, подписки.

ЗАЧЕМ (пункт 2 владельца, 19.10.2026). В чеках не только продукты: такси, перевозка
пассажиров, авансовый платёж, аренда, сборка заказа, подписка. Отчёт привязки считал их
«товарами, которых нет в базе», и владелец видел провал там, где искать было нечего:
из 816 непривязанных товаров боевого рабочего места 80 — услуги и не продукты.

ЗДЕСЬ СТОРОЖА ПРАВИЛА. Маркер услуги — отдельным словом или начало слова, либо фраза;
товарный признак (граммовка, «%», «набор», «корм», «средство», «сборная») сильнее
маркера. Ложное срабатывание дороже пропуска: пропущенная услуга останется в «не
найдено», а выкинутый товар владелец не увидит вовсе. Поэтому в конце — прогон на
дословных названиях боевого замера 19.10.2026 (рабочее место 79990000001, 824
непривязанных названия; из них распознано 107). Три строки с номерами лицевых счетов и
именем человека в фикстуру не клал — это личные данные, а вид строки проверяется
синтетическими тестами выше.
"""
