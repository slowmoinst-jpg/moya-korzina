def _head(text: str) -> str:
    """Начало и конец видимого текста одной строкой — там живут шапка и нижняя панель."""
    whole = (text or "").lower().replace("ё", "е")
    if len(whole) <= HEAD_CHARS + TAIL_CHARS:
        return whole
    return whole[:HEAD_CHARS] + " … " + whole[-TAIL_CHARS:]


def logged_in(chain: str, page_text: str) -> bool | None:
    """Вошёл ли человек. None — «страница не сказала», и это не то же, что «нет»."""
    head = _head(page_text)
    if not head.strip():
        return None
    if re.search(GUARD, head):
        return None                      # это не магазин, а его проверка
    if re.search(STRONG_IN, head):
        return True
    if re.search(ANONYMOUS, head):
        return False
    return None


def guard_kind(page_text: str) -> str:
    """Что пришло вместо витрины: «check», «blocked» или пусто.

    Порядок здесь важнее, чем кажется. Лента на одной странице пишет и «Не удалось
    загрузить сайт», и «Проверка браузера» — и это всё-таки проверка: на ней есть
    что нажать. Поэтому сначала спрашиваем про проверку и только потом про глухую
    страницу, иначе человека послали бы нажимать туда, где кнопок нет.
    """
    head = _head(page_text)
    if re.search(CHECK, head):
        return "check"
    # Отказ по адресу спрашиваем ДО глухой страницы: у Ленты на этой же странице
    # стоит и «403 Forbidden», и общие слова, а совет у двух случаев разный —
    # глухую можно обновить, отказ по адресу не лечится с нашей стороны вовсе.
    if re.search(FORBIDDEN, head):
        return "forbidden"
    if re.search(BLOCKED, head):
        return "blocked"
    return ""


def needs_store(page_text: str) -> bool:
    """Ждёт ли сеть выбранного магазина. Третья причина пустой корзины — см. выше.

    Смотрим по ВСЕМУ видимому тексту, а не по началу и концу, как признак входа:
    окно выбора магазина сеть рисует поверх страницы, и в разметке оно оказывается
    где угодно — у Магнита между шапкой и витриной.
    """
    return bool(re.search(NEEDS_STORE, (page_text or "").lower().replace("ё", "е")))


def guarded(page_text: str) -> bool:
    """Встретила ли нас вообще не витрина — проверка или отказ отдать страницу."""
    return bool(guard_kind(page_text))


def account(chain: str, page_text: str) -> str | None:
    """Подпись аккаунта: номер карты или имя. Не нашли — None, и это важно.

    Здесь стоял возврат общего имени карты сети («Карта Магнит Плюс») на случай,
    когда номера не видно. Оно и вылезло на первой живой странице: гостю имя карты
    показывают в меню, и приложение подписало им кабинет, в который никто не
    входил. Общее имя — украшение для ВОШЕДШЕГО, и подставляет его тот, кто знает,
    что человек вошёл (app/shopbrowser/driver.look), а не этот разбор.
    """
    head = _head(page_text)
    for pattern in ACCOUNT.get(chain, []):
        found = re.search(pattern, head)
        if not found:
            continue
        piece = found.group(1)
        if piece.isdigit():
            return f"{CARD_NAME.get(chain, chain)} •••{piece}"
        return f"{CARD_NAME.get(chain, chain)} ({piece.capitalize()})"
    return None


def points(page_text: str) -> float | None:
    """Баллы. Нет — None, а не ноль: ноль баллов и непрочитанные баллы разные вести."""
    found = re.search(POINTS, _head(page_text))
    if not found:
        return None
    try:
        return float(found.group(1).replace(" ", "").replace(" ", ""))
    except ValueError:
        return None


def entrance(chain: str) -> dict | None:
    """Подсказка по входу в сеть — готовой к показу. Незнакомая сеть — None.

    Отдаём словарём, а не объектом: экрану нужен обычный набор строк, и таскать в
    шаблон наш класс значило бы завязать вёрстку на его поля. Последний шаг
    («на странице главнее») дописывается здесь, чтобы не повторять его шесть раз
    руками и не забыть в седьмой.
    """
    known = ENTRANCE.get(chain)
    if not known:
        return None
    return {"where": known.where, "steps": list(known.steps) + [LAST_STEP],
            "sign": known.sign, "trouble": known.trouble}


def verdict_words(entered: bool | None, *, guard: str = "",
                  account: str | None = None) -> tuple[str, str]:
    """Что сказать человеку про вход и каким тоном: (слова, тон).

    ПОЧЕМУ СЛОВА СЧИТАЮТСЯ ЗДЕСЬ, А НЕ В JAVASCRIPT ЭКРАНА. Это тот же вердикт,
    что и logged_in выше, только вслух, и врать он может ровно так же. В экране
    его нельзя ни проверить без браузера, ни увидеть в наборе тестов — а «не
    разобрал», превратившееся по дороге в «вы не вошли», стоит человеку живого
    подключения. Здесь оно проверяется поддельной страницей за миллисекунду.

    Тон отдаётся отдельным словом («ok», «info», «»), а не цветом: цвет — дело
    экрана. Проверка «я не робот» идёт «info», а не «bad», нарочно: это обычная
    встреча браузера с сетью, и красная плашка объявила бы сломанным то, что
    работает.

    `guard` — не «да/нет», а ЧТО ИМЕННО пришло вместо витрины (guard_kind выше).
    Одно слово на оба случая обещало бы человеку проверку там, где сеть просто не
    отдала страницу, — и он искал бы на ней кнопки, которых нет.
    """
    if guard == "forbidden":
        return FORBIDDEN_NOTE, "info"
    if guard == "blocked":
        return BLOCKED_NOTE, "info"
    if guard:
        return GUARD_NOTE, "info"
    if entered is True:
        return ("Похоже, вы вошли" + (f": {account}" if account else "") +
                ". Можно нажимать «Запомнить вход».", "ok")
    if entered is False:
        return "Вы пока не вошли — войдите в окне ниже, шаги над ним.", ""
    return ("Не разобрал, вошли вы или нет: страница об этом не сказала. "
            "Посмотрите сами — вам видно ровно то же, что и нам.", "")


def logged_in_by_cookies(chain: str, cookies) -> bool | None:
    """Вошёл ли человек — по куке, которую сеть ставит именно после входа.

    Доказательство сильнее текста: оно не зависит от вёрстки вообще. Но работает
    только там, где имя куки известно достоверно; для остальных сетей ответ —
    None, и это честнее выдуманного имени.
    """
    names = AUTH_COOKIE.get(chain) or ()
    if not names:
        return None
    for cookie in cookies or []:
        try:
            name = cookie.get("name")
            value = cookie.get("value")
        except AttributeError:
            continue
        if name in names and value and str(value).strip():
            return True
    return None


