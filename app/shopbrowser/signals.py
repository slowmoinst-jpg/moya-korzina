@dataclass(frozen=True)
class Entrance:
    """Как войти в одну сеть: где вход, что нажимать, по чему видно, что вошли."""

    where: str                      # где на странице искать вход
    steps: tuple[str, ...]          # по шагу на действие, в том порядке, в каком их делают
    sign: str                       # по чему видно, что вход состоялся
    trouble: str = ""               # чем эта сеть встречает именно наш сервер


