# слово -> канонический тип
_WORD_TO_TYPE: dict[str, str] = {
    word: kind for kind, words in TYPE_GROUPS.items() for word in words
}

_WORDS = re.compile(r"[а-яa-z]+", re.I)
_LATIN = re.compile(r"[a-z][a-z0-9]{2,}", re.I)

# латиница, которая маркой не является
NOT_A_BRAND: frozenset[str] = frozenset({
    "kg", "ml", "pcs", "new", "fresh", "light", "classic", "original", "premium",
    "mini", "maxi", "extra", "gold", "plus", "pro", "max", "eco", "bio", "zero",
    "cream", "cheese", "milk", "juice", "water", "www", "com",
})


def product_type(raw: str) -> str | None:
    """Родовое слово названия: «Сыр Страчателла 200 г» -> «сыр».

    Ищем по сырому названию: normalize_name выбрасывает родовые слова как мусор,
    а нам нужно ровно оно.
    """
    text = (raw or "").lower().replace("ё", "е")
    for word in _WORDS.findall(text):
        kind = _WORD_TO_TYPE.get(word) or _WORD_TO_TYPE.get(word.replace("е", "ё"))
        if kind:
            return kind
    return None


def brands(raw: str) -> set[str]:
    """Латинские слова названия — в русских каталогах это почти всегда марка."""
    found = {word.lower() for word in _LATIN.findall(raw or "")}
    return {word for word in found if word not in NOT_A_BRAND}


def type_conflict(left: str, right: str) -> bool:
    """Родовые слова видны с обеих сторон и они разные."""
    a, b = product_type(left), product_type(right)
    return bool(a and b and a != b)


def brand_conflict(left: str, right: str) -> bool:
    """Марки видны с обеих сторон и не пересекаются."""
    a, b = brands(left), brands(right)
    return bool(a and b and not (a & b))


def doubts(product, candidate_name: str, candidate_weight_g=None,
           tolerance_pct: float = 20) -> list[str]:
    """Признаки того, что кандидат выбран зря. Пустой список — возражений нет."""
    from app.matcher.normalize import parse_weight, weight_ok

    name = getattr(product, "name", "") or ""
    out: list[str] = []
    if type_conflict(name, candidate_name):
        out.append(f"тип: {product_type(name)} ≠ {product_type(candidate_name)}")
    if brand_conflict(name, candidate_name):
        out.append("бренд")
    weight = candidate_weight_g
    if weight is None:
        weight = parse_weight(candidate_name)[0]
    if not weight_ok(getattr(product, "weight_g", None), weight, tolerance_pct):
        out.append("вес")
    return out
