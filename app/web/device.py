"""Телефон в роли рук: как сайт узнаёт, что открыт внутри своего приложения.

ЗАЧЕМ ЭТО НУЖНО. По целевой схеме (документ «Единая архитектура», 16.10.2026)
экран один — веб-страницы сервера, — а телефон делает то, что серверу не дают:
входит в кабинеты сетей, ходит туда, куда серверному адресу хода нет. Чтобы
экран мог позвать телефон, он обязан знать, ГДЕ он открыт: в обычном браузере
кнопка «Войти с телефона» была бы мёртвой, а внутри приложения окно входа на
сервере — лишним кругом.

КАК УЗНАЁТ. Приложение на телефоне добавляет в свой User-Agent метку
«KorzinaApp/<версия>» (android/app, MainActivity.setUpWeb). Метка видна уже в
первом запросе, поэтому кнопки моста рисуются сразу, сервером, а не дорисовываются
скриптом после загрузки — без мигания и без «кнопка появилась через секунду».

ДВЕ ПОЛОВИНЫ ОДНОГО УЗНАВАНИЯ. Этот модуль — серверная: шаблоны. Вторая —
клиентская: window.Korzina, который приложение вставляет в страницу
(static/korzina-device.js). Они проверяют одно и то же двумя независимыми
путями нарочно: UA может соврать или потеряться в прокси, мост может не успеть
встать к первому кадру — а действие должно быть доступно всегда, когда оно
возможно.

ДВА РАЗНЫХ ВОПРОСА. on_phone() — «наше приложение»: от этого зависит мост к телефону,
и обычный браузер им не станет. on_mobile() — «любой телефон»: приложение или Safari
и Chrome знакомого, которому с главной нужны телефонные экраны (app/web/phone/), а не
веб для компьютера.

ЧЕГО ЗДЕСЬ НЕТ. Очереди задач: «телефон недоступен, подожди» — это следующий
шаг (GET /api/device/tasks). Здесь телефон отвечает, только пока приложение
открыто и страница на экране.
"""
from __future__ import annotations

from flask import request

# Метка в User-Agent приложения. Слэш в конце — часть метки: без неё слово
# «KorzinaApp» в чужой строке (например, у расширения) давало бы ложный ответ.
MARK = "KorzinaApp/"

# Слова User-Agent обычного браузера на телефоне: Chrome и Safari телефона пишут
# «Mobile», планшет Android — «Android», iPad — «iPad». У браузера компьютера их нет.
MOBILE_WORDS = ("Mobile", "Android", "iPhone", "iPad")


def app_version() -> str | None:
    """Версия приложения из User-Agent или None, если пришёл обычный браузер."""
    ua = request.headers.get("User-Agent") or ""
    at = ua.find(MARK)
    if at < 0:
        return None
    tail = ua[at + len(MARK):]
    # Версия идёт до первого пробела: дальше могут стоять чужие слова строки.
    return tail.split(None, 1)[0].strip() or None


def on_phone() -> bool:
    """Правда ли, что страницу открыло приложение на телефоне владельца."""
    return app_version() is not None


def on_mobile() -> bool:
    """Правда ли, что сайт открыт на телефоне: нашим приложением или обычным браузером."""
    ua = request.headers.get("User-Agent") or ""
    return on_phone() or any(word in ua for word in MOBILE_WORDS)


def install(flask_app) -> None:
    """Отдать узнавание в шаблоны: device_phone и device_app у каждой страницы."""

    @flask_app.context_processor
    def _device():
        return {"device_phone": on_phone(), "device_app": app_version()}


__all__ = ["MARK", "MOBILE_WORDS", "app_version", "on_phone", "on_mobile", "install"]
