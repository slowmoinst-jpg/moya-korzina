def _thresholds() -> list[dict]:
    """Пороги, ради которых перебор иногда берёт дороже. Числа — свои, не пример.

    Экран в Streamlit показывал здесь, насколько близко чеки ПОСЧИТАННОГО варианта
    подошли к порогам, и брал их из session_state — памяти, которой у страницы с
    адресом нет и быть не должно. Сам расчёт живёт на «Результате», и тащить его
    сюда значило бы считать корзину второй раз ради иллюстрации. Поэтому здесь
    стоят сами пороги: они и есть причина, по которой «дешевле по строке» и
    «выгоднее итогом» — разные вещи.
    """
    rows = []
    for store in repo.list_stores():
        offers = repo.offers_for_store(store.id)
        checks = [o.min_check_rub for o in offers if o.min_check_rub]
        if not offers:
            cashback = "карт для этой сети не заведено"
        elif checks:
            cashback = f"кэшбэк включается с чека от {rub(min(checks))}"
        else:
            cashback = "кэшбэк идёт с первого рубля"
        if store.free_delivery_from:
            delivery = (f"доставка {rub(store.delivery_fee)}, "
                        f"бесплатно от {rub(store.free_delivery_from)}")
        elif store.delivery_fee:
            delivery = f"доставка {rub(store.delivery_fee)} всегда"
        else:
            delivery = "доставка бесплатная"
        rows.append({"code": store.code, "name": store.name,
                     "delivery": delivery, "cashback": cashback})
    return rows


def _prices() -> list[dict]:
    """Кто как отдаёт цены — тем же словом, что на «Магазинах». Своей копии нет.

    Список сетей и их состояний — не наш: он принадлежит экрану «Магазины», где
    человек с этим и работает. Здесь он в сокращении, чтобы «откуда берутся данные»
    не оказалось разделом без цен.
    """
    rows = []
    for store in repo.list_stores():
        state, what = HOW.get(store.code, (None, "Источник цен не описан."))
        colour, label = BADGE.get(state, ("var(--ink3)", "не описано"))
        rows.append({"code": store.code, "name": store.name, "colour": colour,
                     "label": label, "what": what})
    return rows


def _shops(depth: int) -> str:
    """«5 магазинов», «2 магазина», «1 магазин» — но никогда «5 магазина».

    Число берётся из настройки и потому бывает любым. Склеенное «{n} магазина»
    было верным ровно при двойке, а при пятёрке экран честности начинал спотыкаться
    на первом же слове — и дальше его читают уже с недоверием. Правило русского
    счёта короткое, и держать его здесь дешевле, чем объяснять потом опечатку.
    """
    tail, hundred = depth % 10, depth % 100
    if tail == 1 and hundred != 11:
        word = "магазин"
    elif tail in (2, 3, 4) and hundred not in (12, 13, 14):
        word = "магазина"
    else:
        word = "магазинов"
    return f"{depth} {word}"


def _status() -> list[tuple[str, str, str, str]]:
    """Строки состояния с подставленной глубиной перебора.

    Число магазинов — настройка (optimizer.max_stores), а не свойство расчёта.
    Вписанное в текст «два магазина» устарело бы в тот день, когда её поменяют, и
    экран честности начал бы врать первым.
    """
    from app import config

    depth = int(config.get("optimizer.max_stores", 2) or 2)
    shops = _shops(depth)
    return [(part, state, label.format(stores=depth, shops=shops),
             detail.format(stores=depth, shops=shops))
            for part, state, label, detail in STATUS]


