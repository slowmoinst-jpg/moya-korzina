def _points() -> dict[str, list]:
    """По какой точке грузится каждая сеть. Пусто — точек у сети не бывает."""
    try:
        from app import places
        return {chain: places.points(chain) for chain in places.BY_POINT}
    except Exception as exc:  # noqa: BLE001 — подбор точки не повод ронять экран
        log.warning("точки не подобрались (%s)", exc)
        return {}


def _catalog() -> dict:
    try:
        from app.catalog import store as catalog_store
        return catalog_store.chain_counts()
    except Exception:  # noqa: BLE001
        return {}


def _saved_logins() -> set[str]:
    """Сети, вход в которые уже сохранён в рабочем месте.

    Нужно ровно для одного: не звать человека нажимать «Обновить цены» там, где
    нажатие сразу упрётся в «вход не сохранён». Обещание, которое отказом и
    кончается, хуже молчания — а на экране честности оно ещё и подрывает всё
    остальное, что здесь написано.

    Берётся НЕ из store_accounts.connection: подключение там ставится отчётом о
    сборе, а не входом, и сегодня почти всегда погашено. Сохранённый вход —
    app/shopbrowser/store.py.
    """
    try:
        from app.shopbrowser import store as shopstore
        return set(shopstore.saved_stores())
    except Exception as exc:  # noqa: BLE001 — нет браузера, нет и беды: просто не знаем
        log.warning("сохранённые входы не прочитались (%s)", exc)
        return set()


def _we_do(code: str, by_cabinet: bool) -> str:
    """Что ПРИЛОЖЕНИЕ делает с сохранённым входом — а не что сеть даёт вошедшему.

    ЗАЧЕМ ЭТО ПОЯВИЛОСЬ. Подписью к нашей кнопке «Войти» стоял список возможностей
    сети: «персональные цены, личные купоны, баллы и кэшбэк, наполнение корзины,
    история покупок». Список честный — но он про СЕТЬ, а человек читает его как
    обещание приложения. Купоны и историю покупок приложение под этим входом не
    забирает вовсе, и половина строки была обещанием, которого никто не выполняет.
    На экране честности это худший сорт дефекта: он не ломает ничего и портит всё.

    ОТКУДА БЕРУТСЯ СЛОВА. Из того, что действительно написано: цены в кабинете
    собираются только у сетей с меткой «Цены из вашего кабинета»
    (app/shopbrowser/collect.CHAINS), корзину браузер наполняет там, где она не
    уезжает ссылкой (app/handover.KIND_BY_STORE), а подпись карты и баллы
    считываются один раз, в момент входа (app/web/screens/cabinet.py).
    """
    try:
        from app import handover as ho
        by_link = ho.KIND_BY_STORE.get(code) == ho.LINK
    except Exception:  # noqa: BLE001 — способ передачи не повод ронять экран
        by_link = False

    tail = ("Купоны и историю покупок оно не забирает; подпись карты и баллы "
            "запоминает один раз, в момент входа, — если сеть их показала.")
    if by_cabinet:
        return ("Под этим входом приложение читает цены с вашей картой и кладёт "
                "посчитанную корзину в ваш кабинет. ") + tail
    if by_link:
        return ("Корзина уезжает в эту сеть ссылкой и без входа, так что сохранённый "
                "вход приложению сегодня почти ничего не добавляет. ") + tail
    return "Под этим входом приложение кладёт посчитанную корзину в ваш кабинет. " + tail


def page():
    points = _points()
    catalog = _catalog()
    logins = _saved_logins()
    rows = []
    for store in repo.list_stores():
        state, what = HOW.get(store.code, (STATE_MANUAL, "Источник цен не описан."))
        colour, label = BADGE[state]
        spots = points.get(store.code) or []
        conn = store_accounts.connection(store.code)
        store_coupons = collector.coupons(store.code)
        rows.append({
            "code": store.code,
            "name": store.name,
            "colour": colour,
            "label": label,
            "what": what,
            # Цены этой сети видит только кабинет человека — и видит их, пока вход
            # сохранён. Две отметки, а не одна: первая про дорогу, вторая про то,
            # открыта ли она сегодня.
            "by_cabinet": state == STATE_CABINET,
            "login_saved": store.code in logins,
            "delivery": store.delivery_fee,
            "free_from": store.free_delivery_from,
            "catalog": catalog.get(store.code),
            "point": "; ".join(p.label or p.address for p in spots) if spots else None,
            "needs_point": store.code in points and not spots,
            # Точка есть, а живые цены по ней расчёт не спрашивает (Пятёрочка,
            # Самокат: прайс, чеки, кабинет). Без этой отметки строка «загружается
            # по точке» читалась обещанием местных цен, которого код не выполняет.
            "point_prices": store.code in location.ADDRESS_STORES,
            "account": conn,
            "coupons": store_coupons,
            "coupons_updated_at": collector.coupons_updated_at(store.code),
            # Что делает ПРИЛОЖЕНИЕ, а не что даёт сеть. Список возможностей сети
            # (store_accounts.describe) отсюда убран: он верен, но читался подписью
            # к нашей кнопке как наше обещание — а половину из него приложение не
            # выполняет. Список сети остался на «Кабинетах», где он к месту.
            "we_do": _we_do(store.code, state == STATE_CABINET),
            "entry": store_accounts.entry_url(store.code),
        })

    return render_template("stores.html", screen=SCREEN_BY_KEY["stores"], rows=rows)


