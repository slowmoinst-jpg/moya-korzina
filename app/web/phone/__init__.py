"""Приложение на телефоне: четыре экрана, выбранные владельцем 17.10.2026.

ЧТО ЭТО. Владелец увидел приложение так: «максимально просто» — Настройки, Корзина,
История заказов и «Где дешевле», и больше ничего (docs/design/ekrany-telefona-2026-10-17.md,
макеты — канва «Моя корзина — приложение на телефоне»). Веб на компьютере остаётся
прежним, со всеми экранами: это вторая раскладка ТЕХ ЖЕ данных, а не второе
приложение. Корзина, заказы, расчёт и передача корзины в магазин берутся у веба
как есть — здесь только то, что рисует телефон.

ЖИВЁТ ПО АДРЕСАМ /phone/…, а телефон — приложение (метка KorzinaApp в User-Agent) или
обычный браузер на телефоне, Safari и Chrome знакомого (app/web/device.py, on_mobile) —
попадает сюда с главной само. Полная версия открывается ссылкой «Полная версия» из
Настроек, то есть адресом /?web=1: экраны веба никуда не делись, и к ним нужен ход, пока
телефонная часть умеет не всё. Ход без памяти — он живёт в адресе, а не в куке: ссылка
на главную (марка в шапке веба) возвращает к телефонным экранам, и это же путь назад.

КАКАЯ КОРЗИНА «ТЕКУЩАЯ». Та же, что открыта в вебе, — настройка `basket:last`
(app/web/screens/basket.py, LAST_OPEN). Если её нет или корзина удалена — самая
свежая. «Повторить» заводит новую корзину и записывает её открытой; вернуться к
прежней можно экраном «Корзины» (/phone/baskets). Телефон и компьютер показывают
одну и ту же корзину, и приложение собирает в магазинах именно её: номер корзины
уезжает ему со страницы (app/phonecart.py).

ПЛОТНОСТЬ. «Элементы экрана по сравнению с текстом очень большие» (владелец, 17.10):
стиль — app/web/static/phone.css, свой, не korzina.css.
"""
from __future__ import annotations

from flask import g, redirect, request, url_for

from app.web import device

from .common import WHERE, bp, deliveries, goods, qty_label, where
from . import basket, cheaper, orders, receipts, settings


# ---------- вход с телефона ----------
def install(flask_app) -> None:
    """Повесить телефонные экраны и привести телефон к ним с главной."""
    flask_app.register_blueprint(bp)

    @flask_app.before_request
    def _phone_home():
        # Только главная и только на телефоне (приложение или его браузер): ссылки на
        # экраны веба, закладки и браузер компьютера живут как жили. «?web=1» — ход в
        # полную версию.
        if (request.method == "GET" and request.path == "/" and device.on_mobile()
                and not request.args.get("web") and getattr(g, "phone", None)):
            return redirect(url_for("phone.basket"))
        return None


__all__ = ["bp", "install", "WHERE", "where", "goods", "deliveries", "qty_label"]
