# Ключ в настройках рабочего места: подключения хранятся в базе человека, не в общей.
KEY = "store_accounts"


@dataclass
class Connection:
    """Состояние подключения одной сети. Секретов здесь нет и быть не должно."""

    store_code: str
    connected: bool = False
    connected_at: str | None = None
    last_seen_at: str | None = None        # когда сборщик последний раз отчитался
    account: str | None = None             # как магазин называет человека: имя, номер карты
    gives: tuple[str, ...] = ()            # что реально пришло, а не что обещано
    points: float | None = None            # баллы программы лояльности
    note: str = ""

    def as_dict(self) -> dict:
        return {"store_code": self.store_code, "connected": self.connected,
                "connected_at": self.connected_at, "last_seen_at": self.last_seen_at,
                "account": self.account, "gives": list(self.gives),
                "points": self.points, "note": self.note}


def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def _load() -> dict[str, dict]:
    raw = repo.get_setting(KEY)
    if not raw:
        return {}
    try:
        data = json.loads(raw)
    except (TypeError, ValueError):
        log.warning("подключения магазинов не прочитались — начинаю с пустого")
        return {}
    return data if isinstance(data, dict) else {}


def _save(data: dict[str, dict]) -> None:
    repo.set_setting(KEY, json.dumps(data, ensure_ascii=False))


def connection(store_code: str) -> Connection:
    """Состояние подключения сети. Не подключена — тоже ответ, а не пустота."""
    raw = _load().get(store_code) or {}
    gives = tuple(str(g) for g in (raw.get("gives") or ()))
    return Connection(
        store_code=store_code,
        connected=bool(raw.get("connected")),
        connected_at=raw.get("connected_at"),
        last_seen_at=raw.get("last_seen_at"),
        account=raw.get("account"),
        gives=gives,
        points=raw.get("points"),
        note=str(raw.get("note") or ""),
    )


def connections() -> list[Connection]:
    """Все сети, где вход вообще что-то даёт, — в порядке справочника магазинов."""
    order = [s.code for s in repo.list_stores()]
    codes = [c for c in order if c in ABILITIES] + [c for c in ABILITIES if c not in order]
    return [connection(code) for code in codes]


def mark_connected(store_code: str, *, account: str | None = None,
                   gives: tuple[str, ...] | list[str] | None = None,
                   points: float | None = None,
                   note: str = "") -> Connection:
    """Записать, что сборщик увидел человека вошедшим в этой сети.

    Вызывается не кнопкой «подключить», а отчётом сборщика: подключение — это не
    наше намерение, а наблюдаемый факт. Человек вышел из аккаунта в магазине —
    следующий отчёт придёт без признака входа, и подключение погаснет само.
    """
    if store_code not in ABILITIES:
        raise ValueError(f"для сети «{store_code}» вход ничего не даёт")
    data = _load()
    was = data.get(store_code) or {}
    now = _now()
    data[store_code] = {
        "connected": True,
        "connected_at": was.get("connected_at") or now,
        "last_seen_at": now,
        "account": account or was.get("account"),
        "gives": list(gives if gives is not None else ABILITIES[store_code].gives),
        "points": points if points is not None else was.get("points"),
        "note": note or was.get("note") or "",
    }
    _save(data)
    log.info("%s: подключение подтверждено сборщиком", store_code)
    return connection(store_code)


def forget(store_code: str) -> None:
    """Забыть подключение у нас. Доступ это НЕ отзывает — он и не у нас.

    Разница важна и проговаривается на экране: чтобы отобрать у приложения доступ
    к своему аккаунту, человек выходит из него в самом магазине. Здесь мы лишь
    перестаём считать, что он вошёл.
    """
    data = _load()
    if data.pop(store_code, None) is not None:
        _save(data)
        log.info("%s: подключение забыто", store_code)


def gives(store_code: str) -> tuple[str, ...]:
    """Что подключение этой сети даёт сейчас: то, что реально пришло от сборщика."""
    state = connection(store_code)
    return state.gives if state.connected else ()


def can(store_code: str, ability: str) -> bool:
    return ability in gives(store_code)


def entry_url(store_code: str) -> str | None:
    """Куда человеку идти, чтобы войти. Вход всегда на стороне магазина."""
    ability = ABILITIES.get(store_code)
    return ability.entry if ability else None


def describe(store_code: str) -> str:
    """Одной строкой: что даст вход в эту сеть. Для экрана."""
    ability = ABILITIES.get(store_code)
    if not ability:
        return "Вход в эту сеть приложению ничего не даёт."
    names = ", ".join(ABILITY_NAMES[g] for g in ability.gives if g in ABILITY_NAMES)
    return f"Вход даёт: {names}." + (f" {ability.note}" if ability.note else "")


