"""Артикул сети из адреса карточки — товар нашёл человек в телефоне, а не сервер.

ЗАЧЕМ. Пятёрочку и Самокат сервер не пускает ни с серверного адреса, ни с домашнего
(замер 18.10.2026: 5ka.ru отвечает «Проверьте настройки интернета и VPN», samokat.ru —
«Forbidden», и оба называют IP отправителя). Поэтому каталог этих сетей в единой базе пуст, и
сопоставление их строк не работает. Но человек ходит по их витрине со своего телефона, и
приложение уже рассказывает серверу, что легло в корзину. Если рядом с позицией отчёта придёт
адрес карточки, сервер достанет из него настоящий артикул сети и положит товар в единую базу:
следующий наряд этой сети уже знает товар, а сопоставление получает строку, которой ему не
хватало.

ПРАВИЛО ОДНО НА КАЖДУЮ СЕТЬ. Адреса у сетей разные, и угадывать их нельзя: не узнали
артикул — товар не записываем. Лучше пропустить строку, чем положить в единую базу чужой номер:
по нему наряд положит в корзину сети не тот товар.
"""
from __future__ import annotations

import re

# Адрес → артикул. Правила сняты с самих сборщиков (app/catalog/crawlers), а не выдуманы:
# у Пятёрочки и Самоката — их же функции sku_from_url, у остальных — тот же вид адреса
# карточки, каким они к нам приходят (проверено живыми замерами 16-20.09.2026).
RULES: dict[str, re.Pattern] = {
    # /product/<название>--<артикул>/ (app/catalog/crawlers/pyaterochka.py:48)
    "pyaterochka": re.compile(r"/product/(?:[^/]*--)?(\d+)/?(?:[?#]|$)"),
    # /product/<слаг> — артикула в адресе НЕТ вовсе. Замер 19.10.2026 в окне телефона:
    # /product/khurma-korolyok-500-g, /product/omlet-roll-creative-kitchen-s-file-
    # polosatogo-tuntsa-200-g — ни у одной карточки нет «--цифры». Ключом берём весь
    # слаг: он уникален на витрине, и по нему открывается та же карточка. Прежнее
    # правило искало в хвосте артикул и доставало «g», «l», «rulona», «sht» — мусор,
    # по которому в корзину сети ничего не положить. То же правило живёт в закладке
    # сбора цен (docs/grab-prices.src.js, skuOf) — одной дорогой, а не двумя.
    "samokat": re.compile(r"/product/([^/?#]+)/?(?:[?#]|$)"),
    # /product/<артикул>-<seoCode> (app/catalog/crawlers/magnit.py:75)
    "magnit": re.compile(r"/product/(\d+)(?:-|/|$)"),
    # /product/<название>-<артикул>/ (app/catalog/crawlers/lenta.py:46)
    "lenta": re.compile(r"/product/[^/]+-(\d+)/?(?:[?#]|$)"),
    # /product/<название>-<артикул>/ — артикул буквенно-цифровой
    # (app/catalog/crawlers/dixy.py:65). ВТОРАЯ ФОРМА — /catalog/<раздел>/<подраздел>/<артикул>/:
    # ровно такие адреса отдаёт наш серверный поиск Дикси (замер 21.10.2026,
    # https://dixy.ru/catalog/molochnye-produkty-yaytsa/moloko/2000328870/), и без второй
    # ветки цена с карточки Дикси не находила свою строку.
    "dixy": re.compile(r"/product/[^/]+-([0-9a-z]{6,})/?(?:[?#]|$)"
                       r"|/catalog/(?:[^/]+/)*([0-9]{6,})/?(?:[?#]|$)", re.I),
    # /product/<название>-<артикул>/ — артикул девятизначный
    # (app/catalog/crawlers/monetka.py:45)
    "monetka": re.compile(r"/product/[^/]+-(\d{6,})/?(?:[?#]|$)"),
    # /catalog/<раздел>/p-<артикул>-<название> (живой образец 20.09.2026)
    "fixprice": re.compile(r"/p-(\d+)(?:-|/|$)"),
    # /cat/<раздел>/p/<название>-<артикул> — адреса из самой базы (замер 19.10.2026):
    # /cat/58/p/bliny-s-masom-zamorozennye-morozko-370g-3342904
    "perekrestok": re.compile(r"/p/(?:[^/?#]*-)?(\d{5,})/?(?:[?#]|$)"),
    # /product/<название>--<артикул> — адреса из самой базы (замер 19.10.2026):
    # /product/linakva-linakva-bebi-0-9-aerozol-150-ml--1284993
    "vprok": re.compile(r"/product/(?:[^/?#]*--)?(\d{4,})/?(?:[?#]|$)"),
}

# Сети, чей адрес карточки нам неизвестен: у них артикул из адреса не берём.
UNKNOWN: tuple[str, ...] = ("metro", "vkusvill")

__all__ = ["RULES", "UNKNOWN", "sku_of"]


def sku_of(chain: str, url: str | None) -> str | None:
    """Артикул сети из адреса карточки. None — сеть не узнана или адрес не её.

    Адрес проверяется по списку хостов сети (app/cartrecord.CHAIN_HOSTS), а не только по
    виду пути: чужой адрес из отчёта не должен превратиться в артикул этой сети — иначе
    в единую базу попал бы товар, которого у сети нет.
    """
    rule = RULES.get(str(chain or ""))
    if rule is None or not url:
        return None
    if not _own(chain, str(url)):
        return None
    match = rule.search(str(url))
    if not match:
        return None
    # У правила может быть несколько ветвей (например, у Дикси два вида адреса):
    # берём первую НЕПУСТУЮ группу, а не всегда первую.
    return next((group for group in match.groups() if group), None)


def _own(chain: str, url: str) -> bool:
    """Адрес принадлежит этой сети? Нет списка хостов у сети — не придираемся."""
    from app.cartrecord import CHAIN_HOSTS

    hosts = CHAIN_HOSTS.get(chain) or ()
    return not hosts or any(host in url for host in hosts)
