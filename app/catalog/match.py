UNITS = {"г", "гр", "кг", "мл", "л", "шт", "мг", "уп", "пач", "бут"}
_NUMERIC = re.compile(r"^\d+([.,]\d+)?$")
_CAPS = re.compile(r"\b[А-ЯЁA-Z]{3,}\b")
# Как написано название — решает его первое настоящее слово: не число, не единица
# и не короче трёх букв. «Молоко ПРОСТОКВАШИНО 930 мл», «Сыр ЛАМБЕР 230г» — названия
# со строчными, и ЗАГЛАВНЫЕ в них — марка (так пишет Лента). «ПИВО СВЕТЛОЕ 0,45л ж/б»,
# «МОЛОКО … 930мл бзмж» — названия заглавными: строчные хвосты (единицы, тара,
# надписи) не делают каждое слово маркой (ревью 18.10.2026). Цена правила: название,
# начатое заглавной маркой («ЧУДО Йогурт…»), марку из заглавных не даёт — это
# безопасная сторона, склеек вложением становится меньше.
_TOKEN = re.compile(r"[^\W_]+")
_UNIT_TOKENS = frozenset({"г", "гр", "кг", "мг", "мл", "л", "шт", "уп", "x", "х",
                          "g", "gr", "kg", "ml", "l"})


def _mixed_case(name: str) -> bool:
    for token in _TOKEN.findall(name):
        if token[0].isdigit() or len(token) < 3 or token.lower() in _UNIT_TOKENS:
            continue
        return any(ch.islower() for ch in token)
    return False


# Заглавные слова, которые маркой не бывают: обязательные надписи и размеры.
# Замер критики 17.10.2026 на каталоге Дикси: ГОСТ стоял маркой у 30 строк, БЗМЖ —
# у 26, XXL — у 21, и «Молоко … 930мл БЗМЖ» склеивалось с «…Домик в деревне… БЗМЖ».
_NOT_BRAND = frozenset({"гост", "бзмж", "змж", "сзмж", "беззмж", "xxl", "пэт", "тба", "эко",
                        "bio", "ту"})

# Штук в упаковке: «Йогурт 4x125г», «Вода 6*0,5л», «Сок 0,2 л x 3 шт», «Яйца 10 шт»,
# «Чай 25пак*2г», «Чай 100х2г». Фасовка берёт последнее число и считает четыре
# йогурта одним (замер 17.10.2026: «…4x125г» и «…125г» сходились как один товар),
# поэтому число штук — отдельный признак. Молчание — одна штука, и это осознанно:
# «Пиво 0,45 л 6 шт» и «Пиво 0,45 л», «Вода 6 шт 0,5 л» и «Вода 0,5 л» — разные
# покупки, цена различается в разы (ревью 18.10.2026).
#
# Порядок правил: множитель с единицей после второго числа («4x125г», «6х0,5л»,
# «2х10шт», «100х2г») — самый надёжный; затем хвост «x 3 шт»; затем штуки словом
# («10 шт», «25 пакетиков», «16 капсул»); и только потом множитель без единицы —
# он уступает отдельному «N шт» («Мешки 30 шт 50х60» — 30, а не 50). Размеры — не
# штуки: «24x24 см», «10x7x3 см», «29х10м», в латинице адресов «24kh24 sm».
_UNIT_AFTER = r"\s*(?:г|гр|кг|мл|л|шт|g|gr|kg|ml|l|sht)(?![а-яёa-z])"
_NOT_SIZE = r"(?!\d|[.,]\d|\s*[xх×*]\s*\d|\s*(?:см|мм|м|cm|mm|sm|m)\b)"
_MULTI_UNIT = re.compile(r"(?<![\d.,])(\d{1,3})\s*[xх×*]\s*\d+(?:[.,]\d+)?" + _UNIT_AFTER)
_MULTI = re.compile(r"(?<![\d.,])(\d{1,2})\s*[xх×*]\s*\d+(?:[.,]\d+)?" + _NOT_SIZE)
_MULTI_TAIL = re.compile(r"[xх×*]\s*(\d{1,3})\s*шт")
_PIECE_WORDS = (r"шт|пак(?:етик(?:ов|а|и)?|ет(?:ов|а|ы)?)?|капсул|саше|стик(?:ов|а|и)?"
                r"|пирамид(?:ок|ки|ка)?|таблет(?:ок|ки|ка)?")
_PIECES = re.compile(r"(?<![\d.,])(\d{1,3})\s*(?:" + _PIECE_WORDS + r")\.?(?![а-яё])")
# Названия латиницей из адреса карточки (Дикси, Монетка, Перекрёсток, Впрок) пишут
# штуки как «2sht» или «10st», а «х» множителя — как «kh» или «h»: «4kh125g». Без
# этого у них всегда одна штука. Только для названий без кириллицы: в русском
# названии «st» и «h» ничего такого не значат. «h» — множитель, только слитно с
# числами или отдельным словом («48h 150ml» — это часы); «st b» — стеклянная бутылка.
_CYRILLIC = re.compile(r"[а-яё]")
_LAT_X = r"(?:\s*kh\s*|h|\s+h\s+|\s*[x*]\s*)"
_MULTI_UNIT_LAT = re.compile(r"(?<![\d.,])(\d{1,3})" + _LAT_X + r"\d+(?:[.,]\d+)?" + _UNIT_AFTER)
_MULTI_LAT = re.compile(r"(?<![\d.,])(\d{1,2})" + _LAT_X + r"\d+(?:[.,]\d+)?" + _NOT_SIZE)
_MULTI_TAIL_LAT = re.compile(r"(?:[x*]|kh|h)\s*(\d{1,3})\s*(?:sht|st(?!\s*b\b))(?![a-z])")
_PIECES_LAT = re.compile(r"(?<![\d.,])(\d{1,3})\s*(?:sht|st(?!\s*b\b)|paketikov|paketika|pak"
                         r"|kapsul|sashe|sase|stikov|piramidok|tabletok)(?![a-z])")

# ЗАЧЕМ (18.10.2026, находка №5). «УП.12», «КОР. 27», «УПАКОВКА 12 БУТ», «ПАК 6»,
# «0,5Л Х 12» читались одной штукой: слова тары выбрасывает normalize.NOISE_WORDS, а
# pack_count чисел при них не искал. Тогда упаковка METRO или Магнита без штрихкодов
# сильно подтверждалась чеком одной бутылки и уходила в наряд. Число после слова тары
# берём только с левой границей слова и с отсечкой единицы и процента следом — иначе
# «СУП 250Г» читалось бы как 250, «УПАКОВКА 300 Г» как 300, а «КОР. 45%» как 45.
# ЗАЧЕМ (18.10.2026, находка №3 ревью). Отсечка после числа запрещала и запятую, и
# точку вовсе: «Вода, упаковка 12, 0,5 л» не читалась (запятая — разделитель, а не
# дробь), хотя «12,5» числом 12 быть не должно. Запрещаем ровно то, что делает число
# другим: следующую цифру («123» — не 12) и дробный хвост «,5»/«.5».
_PACK_NUMBER = (r"(?!\d|[.,]\d)(?!\s*(?:г|гр|кг|мг|мл|л|шт|см|мм|м|%|g|gr|kg|ml|l)"
                r"(?![а-яёa-z]))")
_WORD_N = re.compile(r"(?<![а-яё])(?:упаковка|упак|уп|коробка|кор|пак|блок)(?![а-яё])\.?\s*"
                     r"(?:по\s+)?(\d{1,2})" + _PACK_NUMBER)
_N_WORD = re.compile(r"(?<![\d.,])(\d{1,3})\s*(?:бут(?:ыл(?:ок|ки|ка))?"
                     r"|уп(?:ак(?:овк[аи]|овок)?)?|кор(?:об(?:ок|ки|ка))?"
                     r"|бан(?:ок|ки|ка)|пач(?:ек|ки|ка))\.?(?![а-яё])")
_TAIL_BARE = re.compile(r"(?:г|гр|кг|мл|л)\.?\s*[xх×*]\s*(\d{1,3})" + _PACK_NUMBER)
# ЗАЧЕМ (18.10.2026, находка №6 ревью). Перекрёсток, Впрок и Монетка пишут названия
# латиницей из адреса карточки — это около двух третей каталога, — а правила упаковки
# словами стояли только в кириллической ветке: «Voda up.12 0,5l» и «Pivo pak 6 0,45l»
# читались одной штукой, и чек одной бутылки сильно подтверждал упаковку. Те же слова
# тары, только транслитом: up(akovka), kor(obka), pak, blok, but(ylka), ban(ka),
# pach(ka). Число после слова — с той же отсечкой (_PACK_NUMBER), что и в кириллице.
_LAT_TARE = (r"upakovka|upak|up|korobka|kor|pak|blok"
             r"|but(?:yl(?:ok|ki|ka))?|ban(?:ok|ki|ka)?|pach(?:ek|ki|ka)")
_WORD_N_LAT = re.compile(rf"(?<![a-z\d])(?:{_LAT_TARE})(?![a-z])\.?\s*"
                         rf"(?:po\s+)?(\d{{1,2}})" + _PACK_NUMBER)
# Число ПЕРЕД словом тары — «12 up», «6 pak» — как в кириллической ветке. Разделитель
# (пробел или точка) обязателен: без него «7up 0,5l» — это напиток «7up», а не семь упаковок.
_N_WORD_LAT = re.compile(rf"(?<![\d.,])(\d{{1,3}})(?:\s+|\.)\s*(?:{_LAT_TARE})\.?(?![a-z])")
# Множитель в латинице — не только «x»: Перекрёсток и Монетка пишут «kh» и «h»
# (_LAT_X), поэтому «voda 0,5l kh 12» — та же упаковка, что «Вода 0,5л х 12».
_TAIL_BARE_LAT = re.compile(r"(?:g|gr|kg|ml|l)\.?\s*" + _LAT_X + r"(\d{1,3})" + _PACK_NUMBER)
# «3в1 стик 20шт»: _PIECES берёт «1 стик» из «3в1», потому что взгляд назад пропускает
# букву. Вырезаем само «N в 1» («3 в 1», «3-в-1», «All in 1», «все в 1») только перед
# правилом штук — иначе «Smile15шт» и «FINISH60ШТ» стали бы одной штукой.
_IN_ONE = re.compile(r"(?:(?<![\d.,])\d{1,2}|\ball|\bвсе|\bвсё)\s*-?\s*(?:в|in|v)"
                     r"\s*-?\s*1(?![\d.,])")


def pack_count(name: str | None) -> int:
    """Сколько штук в упаковке по названию. Не сказано — одна."""
    text = (name or "").lower()
    if _CYRILLIC.search(text):
        rules = (_MULTI_UNIT, _MULTI_TAIL, _PIECES, _N_WORD, _WORD_N, _TAIL_BARE, _MULTI)
        pieces = _PIECES
    else:
        rules = (_MULTI_UNIT_LAT, _MULTI_TAIL_LAT, _PIECES_LAT, _N_WORD_LAT, _WORD_N_LAT,
                 _TAIL_BARE_LAT, _MULTI_LAT)
        pieces = _PIECES_LAT
    for rx in rules:
        probe = _IN_ONE.sub(" ", text) if rx is pieces else text
        found = rx.search(probe)
        if found:
            try:
                return max(1, int(found.group(1)))
            except ValueError:
                return 1
    return 1

# --- ПРОЦЕНТ И РАЗНОВИДНОСТЬ: чем товары отличаются, когда слова одинаковы -----
#
# ЗАЧЕМ. Замер 20.09.2026 на живом каталоге: 188 групп из 7 941 (2,4 %) смешали
# РАЗНЫЕ проценты — «Сметана Большая кружка 15 %» и она же 20 %, майонез 67 % и
# 55 %, пудинг 6 % и 5,2 %. Причина в том, что meaningful() выбрасывает числа как
# шум, и у обеих сметан остаётся один и тот же набор слов. Для покупателя это
# разные товары и разные деньги, а расчёт складывал их в один.
#
# Процент ведёт себя как фасовка: обе стороны молчат или молчит одна — не улика
# (weights_agree уже написан по этому правилу), обе назвали и назвали разное —
# разные товары.
_PCT = re.compile(r"(\d{1,2}(?:[.,]\d)?)\s*%")

# Слова, которые ДЕЛАЮТ товар другим товаром, даже когда всё остальное совпало.
# «Спагетти Barilla 450 г» и «Спагетти Barilla без глютена 400 г» — разные покупки,
# и человек, купивший не то, узнает об этом дома. Поэтому такая метка на одной
# стороне и её отсутствие на другой — веский довод против, а не мелочь.
#
# Список нарочно короткий и из наблюдений: сюда идёт только то, что встретилось
# живым каталогом (замер 20.09.2026 — Curaprox Zero, спагетти без глютена).
# Добавлять сюда «вкусовые» слова нельзя: «малиновый» и «клубничный» различаются
# сами по себе, а вот отсутствие слова метки — это утверждение.
VARIANT_MARKS = {
    "безглютена", "глютенфри", "glutenfree", "безлактозы", "безлактозный",
    "безсахара", "zero", "зеро", "light", "лайт", "легкий",
    "обезжиренный", "обезжиренное", "цельнозерновой", "цельнозерновые",
    "органический", "organic",
}
# ЧЕГО ЗДЕСЬ НЕТ НАРОЧНО, И ЭТО ВАЖНЕЕ ТОГО, ЧТО ЕСТЬ.
#
# «без ЗМЖ» — метка на половине молочного отдела: живой каталог 20.09.2026 полон
# строк вида «jjogurt pitevojj irbitskijj pechenaya grusha 25 bez zmzh 500g». Это
# не разновидность товара, а обязательная надпись, и одна сеть её пишет, другая
# нет. Взяв её меткой, мы развели бы по разным товарам один и тот же йогурт.
#
# «детский» — по той же причине, но с другой стороны: сети пишут его вразнобой,
# «Творожок детский» против «tvorog dlya detejj». Метка на одной стороне и её
# отсутствие на другой означали бы «разные товары» там, где различается только
# оборот речи.
# «без глютена» приходит двумя словами — склеиваем пары «без X» в одно слово,
# иначе «без» потеряется как короткое, а «глютена» останется само по себе и
# встретится с обычным товаром, где его просто нет. Латиница Перекрёстка пишет то
# же самое как «bez sahara», поэтому оба написания склеиваются одинаково.
_WITHOUT = re.compile(r"\b(?:без|bez)\s+(\w+)", re.I)


def parse_percent(name: str | None) -> float | None:
    """Процент из названия: жирность, крепость. «Сметана 15 %» -> 15.0."""
    found = _PCT.search(name or "")
    if not found:
        return None
    try:
        return float(found.group(1).replace(",", "."))
    except ValueError:
        return None


def percents_agree(a: float | None, b: float | None) -> bool:
    """Проценты не спорят: обе неизвестны или одна неизвестна — молчание не улика."""
    if a is None or b is None:
        return True
    return abs(a - b) < 0.05


@lru_cache(maxsize=1)
def _marks_folded() -> frozenset[str]:
    """Метки в общем своде письма — считаются один раз на весь обход."""
    return frozenset(fold(w) for w in VARIANT_MARKS)


def variant_marks(name: str | None) -> frozenset[str]:
    """Метки разновидности: «без глютена», «zero», «обезжиренный», «детская».

    Считаются ПО СВОДУ ПИСЬМА, иначе метка сама бы и ломала межписьменные пары:
    «Каша детская Gipopo» имела бы метку, а kasa detskaa gipopo — нет, и вместо
    защиты от переклейки вышла бы новая дыра в сопоставлении.

    ЗАЧЕМ сравнение началом слова (18.10.2026, находка №14). Чек пишет «Б/САХ» и
    «Б/ЛАКТ», и склеенное «БЕЗСАХ» не равнялось метке «безсахара» — товар с меткой
    не находился вовсе. Короче пяти букв началом слова не сверяем: сам «без» и «беза»
    из «Б/А» меткой не бывают.
    """
    text = (name or "").lower()
    glued = _WITHOUT.sub(lambda m: "без" + m.group(1), text)
    known = _marks_folded()
    words = {fold(w.strip(",.;:()«»\"'")) for w in glued.split()}
    out = {w for w in words if w in known}
    # Начало слова приводим к САМОЙ метке, иначе «Б/САХ» дал бы метку «безсах», а
    # «без сахара» — «безсахара», и они бы снова разошлись.
    for w in words - out:
        if len(w) >= 5:
            out |= {m for m in known if m.startswith(w)}
    return frozenset(out)

# --- ОБЩИЙ СВОД ПИСЬМА: кириллица и чужая латиница как одно слово ------------
#
# ЗАЧЕМ. Перекрёсток и Впрок отдают названия ЛАТИНИЦЕЙ — они берутся прямо из
# адреса карточки: /p/maslo-slivocnoe-icalki-krestanskoe-72-5-500g. Остальные сети
# пишут кириллицей. Для сравнения множеств слов это разные слова без единой общей
# буквы, и замер 20.09.2026 показал цену этого: пару в другой сети нашли 0,2 %
# строк Перекрёстка и 0,6 % Впрока против 6–21 % у сетей с кириллицей. 186 тысяч
# строк, две трети каталога, лежали отдельным островом.
#
# ПОЧЕМУ НЕ ГОТОВАЯ translit ИЗ app/matcher/normalize.py. Она переводит «ч» в «ch»,
# «ш» в «sh», «ж» в «zh» — так пишут в паспортах. У Перекрёстка схема ДРУГАЯ, без
# второй буквы: «сливочное» у него slivocnoe, «Ичалки» — icalki, «крестьянское» —
# krestanskoe. Наша дала бы slivochnoe, ichalki, krestyanskoe — и не совпало бы
# ничего.
#
# ЧТО ДЕЛАЕМ. Сводим ОБЕ стороны к общей краткой форме: и кириллицу, и уже готовую
# латиницу. Диграфы схлопываются в одну букву (ch -> c, sh -> s, zh -> z), парные
# гласные — в одну (yu -> u, ya -> a), «y» приравнивается к «i». Тогда «сливочное»
# и slivocnoe сходятся в slivocnoe, «масло» и maslo — в maslo.
#
# НАПРАВЛЕНИЕ ВЫБРАНО ОДНО: кириллица -> латиница. Обратное породило бы догадки
# («c» — это «с» или «ц»?), а это направление однозначно.
#
# СВОД ОГРУБЛЯЕТ, И ЭТО ОСОЗНАННО: «ч» и «ц» сходятся в «c», «ш» и «щ» — в «s».
# Поэтому он НЕ заменяет строгое сравнение, а идёт вторым заходом, когда строгое
# не нашло совпадения, и под теми же охранами — единица, фасовка, марка.
_FOLD_LETTERS = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "z", "з": "z", "и": "i", "й": "i", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "c", "ч": "c", "ш": "s", "щ": "s", "ъ": "",
    "ы": "i", "ь": "", "э": "e", "ю": "u", "я": "a",
}
# Порядок важен: «sch» должно схлопнуться до того, как за него возьмётся «ch».
_FOLD_DIGRAPHS = (("shch", "s"), ("sch", "s"), ("ch", "c"), ("sh", "s"),
                  ("zh", "z"), ("kh", "h"), ("ts", "c"), ("yu", "u"),
                  ("ya", "a"), ("ye", "e"), ("yo", "e"), ("x", "ks"))


def fold(text: str | None) -> str:
    """Общая краткая форма слова: «сливочное» и «slivocnoe» -> «slivocnoe»."""
    s = (text or "").lower()
    s = "".join(_FOLD_LETTERS.get(ch, ch) for ch in s)
    for pair, one in _FOLD_DIGRAPHS:
        s = s.replace(pair, one)
    # «y» осталась только там, где пришла латиницей: приравниваем её к «i», иначе
    # «krestyanskoe» и «krestanskoe» разойдутся на одну букву.
    s = s.replace("y", "i")
    # «й» часть адресов пишет удвоенным «jj» (Монетка, часть Перекрёстка:
    # «dobryjj» — это «добрый»). Замер 17.10.2026 по разбору каталога: без этого
    # такие строки не встречали кириллицу ни одной сети.
    return s.replace("jj", "i")


def fold_words(words) -> frozenset[str]:
    """Свод набора слов. Пустые после свода отбрасываем: они ничего не различают."""
    return frozenset(w for w in (fold(x) for x in words) if len(w) >= 2)


# --- ТАРА, НАДПИСИ И ОТРИЦАНИЯ: одни правила для базы и для товаров людей ------
#
# ЗАЧЕМ (ревью 18.10.2026). Тару и обязательные надписи одни сети и чеки пишут,
# другие нет: «…0,5Л ПЭТ», «…930МЛ БЗМЖ», «…0,5Л СТ/Б». О товаре они ничего не
# говорят. Пока их убирало только сопоставление товара человека (app/catalog/link.py),
# два товара базы, разошедшиеся одним таким словом, для человека становились равными
# — и выходило «сомнительно». Поэтому чистка здесь, в prepare: её видят и склейка
# базы, и сопоставление людей.
#
# «без X» — одно слово («без газа» → «безгаза»), иначе «без» терялось, и чек «ВОДА …
# ГАЗ» находил «… без газа». «Н/ГАЗ» и «Б/К» в чеке — тоже отрицание: «НЕГАЗ»,
# «БЕЗК». «С ЗМЖ» (с заменителем молочного жира) — слово «СЗМЖ», и оно остаётся:
# такой продукт не равен молочному. Голое «змж» шумом не считается по той же
# причине; шум — «БЗМЖ» и склеенное «без змж».
NOISE = frozenset(fold(w) for w in (
    "пэт", "pet", "тп", "тба", "бзмж", "беззмж", "безгмо", "без",
    "весов", "весовой", "весовая", "весовое", "весовые", "жб", "стб", "плб",
    # СЛУЖЕБНЫЕ СЛОВА — ЭТО НЕ ТОВАР (замер 20.10.2026). Головой корзины берутся два
    # первых смысловых слова названия, и предлог «для», стоящий вторым («Смесь для…»,
    # «Корм для…»), делал корзину из 16 076 строк: перебор 129,2 млн пар — 27,7 % всей
    # работы сопоставления (всего пар 466,4 млн). При этом «для» не отличает один товар
    # от другого: у него нет смысла в названии. Тот же довод у остальных предлогов.
    "для", "из", "на", "по", "от", "до", "со", "во", "об", "при", "под", "над", "за",
))
_LETTER = "А-Яа-яЁёA-Za-z"
# Тара пишется и через косую, и через точки: «СТ/Б», «Ж/Б», «ПЛ.Б.», «СТ.Б.ГАЗ».
# ЗАЧЕМ ЗДЕСЬ ТОЧКА (18.10.2026, находка №8 ревью). Пока правило знало только «/»,
# в «ВОДА СТ.Б.ГАЗ 0,5Л» оставалось «Б.ГАЗ», и _NEG_DOT читал это как «без газа»:
# ГАЗИРОВАННАЯ вода становилась негазированной — не потеря связи, а НЕ ТОТ товар.
# Заодно «СТ» больше не остаётся в названии мусорным словом.
_TARE = re.compile(rf"(?<![{_LETTER}])(?:ст|пл|пэт|ж|с)\s*[/.]\s*б(?:ут)?(?![{_LETTER}])\.?", re.I)
_ZMZH = re.compile(rf"(?<![{_LETTER}])([бБсСbBsS])\s*[/.\-]?\s*(змж|zmzh)(?![{_LETTER}])", re.I)
_SLASH_NEG = re.compile(rf"(?<![{_LETTER}])([нНбБ])\s*/\s*(?=[^\W\d_])")
# ЗАЧЕМ (18.10.2026, находка №2). «Н.ГАЗ», «Б.САХ», «Н-ГАЗ», «Н\ГАЗ» _SLASH_NEG не
# знает (он только про «/»), а link._prep убирал точку раньше склейки — и чек сильно
# подтверждал противоположный товар. Точка, дефис и обратная черта отрицают перед
# ОСНОВОЙ ОТ ДВУХ БУКВ: «Н-Р» (набор) и инициалы «Б.Ю.АЛЕКСАНДРОВ» не трогаются, а
# отрицательный взгляд назад на букву не даёт склеить «БАНАН-КЛУБНИКА». «/» оставлен
# _SLASH_NEG с одной буквой: правило «основа от двух букв» и для «/» ломает «Б/А»
# (светлое пиво подтверждалось бы алкогольным) и «Б/К» (терялось «без кожи»).
_NEG_DOT = re.compile(rf"(?<![{_LETTER}])([нНбБ])\s*[.\\\-]\s*(?=[^\W\d_]{{2}})")
# ЗАЧЕМ (18.10.2026, находка №8 ревью). «Б.А.» и «Б-А» — безалкогольное пиво, а
# _NEG_DOT требует после знака ОСНОВУ ОТ ДВУХ БУКВ (так охраняются «Н-Р» — набор — и
# инициалы «Б.Ю.АЛЕКСАНДРОВ»). У «Б.А.» основа однобуквенная, обе буквы выбрасывались,
# и светлое безалкогольное пиво сходилось с алкогольным — то есть со своим антиподом.
# Здесь ровно этот случай и ничего больше: «Б», точка или дефис, «А» и сразу конец
# слова («Б.А.ИВАНОВ» и «Б.Ю.АЛЕКСАНДРОВ» не трогаются: после «А» — точка и буква,
# то есть инициалы, а не метка). Выход — как у «Б/А» (_slash_neg): «БЕЗА», поэтому
# две записи одного товара читаются одинаково.
_NEG_BA = re.compile(rf"(?<![{_LETTER}])([бБ])\s*[.\-]\s*(?=[аА](?:\.(?![{_LETTER}])|(?![.{_LETTER}])))")
# «НЕ ГАЗ», «НЕ ФИЛЬТР», «НЕ РАФ» — отрицание словом, а не «/»: без этого «не» из двух
# букв выбрасывалось и оставалось «газ», которое сильно подтверждало газированное.
_WITHOUT_WORD = re.compile(r"\b(без|bez|не)(?:\s+|\s*[/\\]\s*)(?=[^\W\d_])", re.I)


def _zmzh(m: re.Match) -> str:
    head, tail = m.group(1), m.group(2)
    latin = head.lower() in "bs"
    if head.lower() in "бb":
        word = "bezzmzh" if latin else "беззмж"
    else:
        word = "szmzh" if latin else "сзмж"
    return word.upper() if (head.isupper() and tail.isupper()) else word


def _slash_neg(m: re.Match) -> str:
    head = m.group(1)
    word = "не" if head.lower() == "н" else "без"
    return word.upper() if head.isupper() else word


def glue(text: str | None) -> str:
    """Тару убрать, отрицания склеить в одно слово. Регистр сохраняется: по нему
    узнаётся марка, и чек целиком заглавными не должен стать «со строчными»."""
    text = _TARE.sub(" ", text or "")
    text = _ZMZH.sub(_zmzh, text)
    text = _SLASH_NEG.sub(_slash_neg, text)
    text = _NEG_BA.sub(_slash_neg, text)
    text = _NEG_DOT.sub(_slash_neg, text)
    return _WITHOUT_WORD.sub(lambda m: m.group(1), text)


def quiet(words) -> list[str]:
    """Слова без тары и надписей (по своду письма), в прежнем порядке."""
    return [w for w in words if fold(w) not in NOISE]


@lru_cache(maxsize=8)
def _folded_vocab(vocab: frozenset[str]) -> frozenset[str]:
    """Свод словаря марок — один раз на обход, а не на каждой паре.

    Словарь марок всего каталога — это тысячи слов, а сравнений сотни миллионов.
    Сводить его внутри same_product значило бы проделать одну и ту же работу
    заново на каждой паре и растянуть сопоставление с двух минут на часы.
    """
    return fold_words(vocab)


@dataclass
class Row:
    """Товар сети, подготовленный к сравнению."""
    id: int
    chain: str
    name: str
    words: frozenset[str]        # смысловые слова названия плюс марка
    order: tuple[str, ...]       # те же слова в порядке названия — для группировки
    brand_words: frozenset[str]  # что мы считаем маркой у этого товара
    brand: str | None            # марка полем сети, как она написана
    weight_g: float | None
    unit: str | None
    barcode: str | None
    category: str | None
    # Те же три набора в общем своде письма (fold): по ним кириллица одной сети
    # встречается с латиницей другой. Считаются один раз здесь, а не при каждом
    # сравнении: свод зовётся на каждой паре, а пар — сотни миллионов.
    fwords: frozenset[str] = frozenset()
    forder: tuple[str, ...] = ()
    fbrand: frozenset[str] = frozenset()
    pct: float | None = None       # жирность, крепость: «Сметана 15 %» -> 15.0
    marks: frozenset[str] = frozenset()   # «без глютена», «zero», «детская»
    # Штрихкод в одном виде (normalize.gtin) — по нему сравнивают и группируют.
    # Сам barcode остаётся как его написала сеть. Замер 17.10.2026: чек отдаёт
    # GTIN-14 с ведущим нулём, METRO — EAN-13, и буквальное сравнение разводило
    # один товар. Приводится только ДОВЕРЕННЫЙ код (normalize.gtin_trusted).
    # Внутренний код магазина (весовая этикетка, свой код сети) у каждой сети
    # свой: такие коды идут подряд с малых номеров и у двух сетей совпадают на
    # разных товарах («Бананы весовые» и «Свинина шея» — ревью 18.10.2026). Его
    # ключ — «сеть#код»: решает он только внутри своей сети.
    bkey: str | None = None
    packs: int = 1                 # штук в упаковке: «4x125г» — четыре


def meaningful(text: str | None) -> frozenset[str]:
    """Смысловые слова: без чисел, единиц измерения и однобуквенного мусора."""
    return frozenset(ordered_words(text))


def ordered_words(text: str | None) -> list[str]:
    out: list[str] = []
    for w in normalize_name(text or "").split():
        if _NUMERIC.match(w) or w in UNITS or w[:1].isdigit() or len(w) < 2 or w in out:
            continue
        out.append(w)
    return out


def weights_agree(a: float | None, b: float | None) -> bool:
    """Фасовки не спорят: обе неизвестны или одна неизвестна — молчание не улика."""
    if not a or not b:
        return True
    tolerance = float(config.get("weight_tolerance_pct", 20) or 20) / 100.0
    return abs(a - b) / max(a, b) <= tolerance


def prepare(product: dict) -> Row:
    name = product.get("name") or ""
    weight = product.get("weight_g")
    if not weight:
        weight, _ = parse_weight(name)
    brand = product.get("brand") or None
    # Слова — по склеенному названию без тары и надписей (glue, NOISE). Само название,
    # процент, метки, штуки и фасовка — по тому, как написала сеть.
    text = glue(name)
    # Заглавные — марка, только если название написано со строчными: так пишет марки
    # Лента («Молоко ПРОСТОКВАШИНО 930 мл»). Название целиком заглавными (строка
    # чека, часть строк Дикси) иначе делало маркой каждое слово, и любое вложение
    # слов проходило как «общая марка» (критика 17.10.2026). Склеенное отрицание
    # («БЕЗГАЗА») маркой не бывает.
    caps = (frozenset(quiet(w for w in meaningful(" ".join(_CAPS.findall(text)))
                            if w not in _NOT_BRAND and not w.startswith("без")))
            if _mixed_case(name) else frozenset())
    own = frozenset(quiet(meaningful(brand)))
    brand_words = own | caps
    order = tuple(quiet(ordered_words(text)))
    words = frozenset(order) | own
    barcode = (str(product["barcode"]).strip() or None) if product.get("barcode") else None
    code = gtin(barcode) if barcode else None
    bkey = None
    if barcode:
        bkey = code if gtin_trusted(code) else f"{product['chain']}#{barcode}"
    # ЗАЧЕМ (18.10.2026, находка №9). Сборщик METRO единицу не ставит вовсе, а в
    # названии пишет «…, весовые». Без этого весовое без единицы склеивалось с
    # фасованным: канон брал единицу одной строки и фасовку другой, и покупатель
    # терял сеть. Слово «весов…» в названии — и есть названная сетью единица.
    unit = product.get("unit") or None
    if unit is None and sold_by_weight(name):
        unit = "kg"
    return Row(id=int(product["id"]), chain=product["chain"], name=name,
               words=words, order=order, brand_words=brand_words,
               fwords=fold_words(words),
               forder=tuple(dict.fromkeys(w for w in (fold(x) for x in order) if len(w) >= 2)),
               fbrand=fold_words(brand_words),
               pct=parse_percent(name), marks=variant_marks(text),
               brand=brand, weight_g=weight or None, unit=unit,
               barcode=barcode, bkey=bkey, packs=pack_count(name),
               category=product.get("category"))


def trusted_key(bkey: str | None) -> bool:
    """Ключ штрихкода — настоящий GTIN, а не внутренний код одной сети."""
    return bool(bkey) and "#" not in bkey


def item_payload(bkey: str | None) -> str | None:
    """12 знаков товара в GTIN-14: без индикатора (первой цифры) и контрольной (последней).

    ЗАЧЕМ (замер 21.10.2026). У одного и того же айрана Метро отдаёт код штуки
    `04680000192903`, а Лента — КОРОБОЧНЫЙ код `14680000192900`: у них общий номер
    товара (468000019290), а различаются индикатор упаковки и контрольная цифра.
    Правило «коды разные — товары разные» держало такие строки врозь, хотя фасовка
    и название совпадали: в базе нашлось 355 групп товаров из разных сетей с одинаковым
    именем, маркой и весом, но разными едиными товарами. Сравнение цен из-за этого
    терялось. Коробочный код — это не улика «другой товар», это молчание о штуке.
    """
    if not bkey or not trusted_key(bkey) or len(bkey) != 14 or not bkey.isdigit():
        return None
    return bkey[1:13]


def same_payload(a: str | None, b: str | None) -> bool:
    """Коды разные, но номер товара у них один (штука против коробки)."""
    left, right = item_payload(a), item_payload(b)
    return bool(left) and left == right and a != b


def same_pack(a: Row, b: Row) -> bool:
    """Число штук не спорит: разное число штук — разные покупки.

    Четыре йогурта по 125 г — не один йогурт 125 г, хотя фасовка из названия у них
    одна (последнее число). Молчание здесь улика, и это осознанно (ревью 18.10.2026):
    «Пиво 0,45 л 6 шт» против «Пиво 0,45 л», «Вода 6 шт 0,5 л» против «Вода 0,5 л»,
    «Сырок 40 г 5 шт» против «Сырок 40 г» — фасовка одной штуки, и правило «молчание
    не улика» вернуло бы ошибку цены в 5–24 раза. Исключения «6 шт 300 г» = «300 г»
    нет: по тексту не отличить общую фасовку пачки от фасовки одной штуки, а не
    связать лучше, чем связать не то.
    """
    return a.packs == b.packs


def _weighed_vs_packed(a: Row, b: Row) -> bool:
    """Весовое без фасовки спорит с невесовой строкой, у которой фасовка названа.

    ЗАЧЕМ (18.10.2026, находка №9). Лента «…, весовые» и METRO «… 250г» склеивались,
    когда единицу назвала только одна сторона: канон брал единицу одной строки и
    фасовку другой. Оговорка «b не kg» обязательна: без неё отрывается весовой товар
    с фасовкой порции (у него unit=kg и вес назван).
    """
    return a.unit == "kg" and not a.weight_g and b.unit != "kg" and bool(b.weight_g)


def compatible(a: Row, b: Row) -> bool:
    """Охраны без слов: ничто, кроме названия, не говорит, что это разные товары.

    Те же проверки, с которых начинается same_product; вынесены, чтобы сопоставление
    товара человека с единой базой (app/catalog/link.py) судило по тем же правилам,
    а не по своим.
    """
    if a.unit and b.unit and a.unit != b.unit:
        return False
    if _weighed_vs_packed(a, b) or _weighed_vs_packed(b, a):
        return False
    if not weights_agree(a.weight_g, b.weight_g):
        return False
    if not same_pack(a, b):
        return False
    # Процент — такая же жёсткая улика, как фасовка. Замер 20.09.2026: без него
    # «Сметана Большая кружка 15 %» и она же 20 % склеивались в один товар, потому
    # что числа выброшены как шум и наборы слов у них одинаковые.
    if not percents_agree(a.pct, b.pct):
        return False
    # Метка разновидности на одной стороне и её отсутствие на другой — довод
    # против. «Спагетти Barilla 450 г» и «Спагетти Barilla без глютена 400 г» —
    # разные покупки, и человек узнаёт об этом уже дома.
    if a.marks != b.marks:
        return False
    # Спор марок проверяется ПО СВОДУ, иначе он сам же и рубит межписьменные пары:
    # «Простоквашино» и prostokvasino общих слов не имеют, и до сравнения названий
    # дело бы не дошло — пара отсеялась бы как «марки спорят».
    if a.fbrand and b.fbrand and not (a.fbrand & b.fbrand):
        return False
    return True


def same_product(a: Row, b: Row, brand_vocab: frozenset[str] = frozenset()
                 ) -> tuple[bool, str, float]:
    """Один ли это товар. Возвращает (да/нет, способ, уверенность)."""
    # Решает штрихкод, если оба кода настоящие или оба внутренние одной сети. Если
    # настоящий только у одной стороны, а у другой — внутренний код магазина, коды
    # ничего не говорят друг о друге: решают слова.
    # КОРОБКА ПРОТИВ ШТУКИ (21.10.2026): если коды разные, но у них ОДИН номер товара
    # (см. same_payload), это не улика «разные товары», а молчание о фасовке: решают слова.
    if a.bkey and b.bkey and (a.chain == b.chain or (trusted_key(a.bkey) and trusted_key(b.bkey))):
        if not same_payload(a.bkey, b.bkey):
            return (a.bkey == b.bkey), "barcode", 1.0
    if not a.words or not b.words:
        return False, "", 0.0
    if not compatible(a, b):
        return False, "", 0.0
    if a.words == b.words:
        return True, "words", 0.95 if (a.weight_g and b.weight_g) else 0.8
    small, big = (a.words, b.words) if len(a.words) <= len(b.words) else (b.words, a.words)
    if small < big and a.weight_g and b.weight_g:
        marks = brand_vocab | a.brand_words | b.brand_words
        if small & marks:
            return True, "words", 0.85

    # Второй заход — по своду письма, и только если строгое сравнение не нашло
    # совпадения. Свод огрубляет («ч» и «ц» в нём одна буква), поэтому уверенность
    # ниже, а охраны — те же самые, они уже отработали выше.
    if a.fwords and b.fwords:
        if a.fwords == b.fwords:
            return True, "translit", 0.9 if (a.weight_g and b.weight_g) else 0.75
        fsmall, fbig = ((a.fwords, b.fwords) if len(a.fwords) <= len(b.fwords)
                        else (b.fwords, a.fwords))
        if fsmall < fbig and a.weight_g and b.weight_g:
            fmarks = _folded_vocab(brand_vocab) | a.fbrand | b.fbrand
            if fsmall & fmarks:
                return True, "translit", 0.8
    return False, "", 0.0


class _Union:
    def __init__(self) -> None:
        self.parent: dict[int, int] = {}

    def find(self, x: int) -> int:
        self.parent.setdefault(x, x)
        while self.parent[x] != x:
            self.parent[x] = self.parent[self.parent[x]]
            x = self.parent[x]
        return x

    def union(self, a: int, b: int) -> None:
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            self.parent[rb] = ra


def brand_vocabulary(rows: list[Row]) -> frozenset[str]:
    """Марки, известные хоть одной сети полем brand или заглавными в названии."""
    out: set[str] = set()
    for r in rows:
        out |= r.brand_words
    return frozenset(out)


def cluster(products: list[dict]) -> list[list[tuple[Row, str, float]]]:
    """Разбить строки каталогов на группы «один товар».

    Кандидаты — товары с общим словом среди первых двух смысловых слов названия
    (обычно это существительное: «молоко», «сыр», «персики»); штрихкоды — отдельный
    индекс. Внутри группы перебор попарный, но группы на порядки меньше каталога.
    """
    rows = [prepare(p) for p in products]
    vocab = brand_vocabulary(rows)
    union = _Union()
    how: dict[int, tuple[str, float]] = {}

    by_barcode: dict[str, list[Row]] = defaultdict(list)
    by_head: dict[str, list[Row]] = defaultdict(list)
    for r in rows:
        if r.bkey:
            by_barcode[r.bkey].append(r)
        # Корзины — ПО СВОДУ ПИСЬМА, а не по самому слову. Иначе «молоко» и moloko
        # попадают в разные корзины и не встречаются никогда: перебор идёт только
        # внутри корзины, и второй заход по своду в same_product до них не дошёл бы.
        for head in r.forder[:2]:
            by_head[head].append(r)

    for group in by_barcode.values():
        for other in group[1:]:
            union.union(group[0].id, other.id)
            how[other.id] = ("barcode", 1.0)
            how.setdefault(group[0].id, ("barcode", 1.0))

    # ЗДЕСЬ БЫЛО МНОЖЕСТВО ВСЕХ СРАВНЁННЫХ ПАР, И ОНО УБИВАЛО СОПОСТАВЛЕНИЕ.
    #
    # Замер 20.09.2026, когда каталог дорос до 262 475 строк: головных слов 30 785,
    # а пар к сравнению 195 342 771 — на одно только множество пар нужно 10,9 ГБ при
    # 7,9 ГБ на сервере. Процесс убивали сигналом, в журнале оставалось одно слово
    # «Killed», и сопоставление не отработало ТРИ ОБХОДА ПОДРЯД: Впрок, Монетка и
    # Fix Price лежали в каталогах сетей, но в единые товары не попадали, а
    # catalog_items стоял на цифрах от 19.09. Снаружи это выглядело как «всё ok».
    #
    # Множество берегло время: пара, попавшая в две корзины сразу, сравнивалась бы
    # дважды. Замер показал, чего это стоило: одно сравнение — 1,2 мкс, все 195 млн
    # пар это ЧЕТЫРЕ МИНУТЫ. То есть память тратилась гигабайтами ради минут.
    #
    # Вместо него — проверка по самому объединению: если строки уже в одной группе,
    # сравнивать их незачем. Она не только бесплатна по памяти, но и отсекает больше
    # работы, чем отсекало множество: пара пропускается и тогда, когда её склеили
    # через третью строку. Потолок на размер корзины не понадобился — он резал бы
    # совпадения у «вино», «сыр», «напиток», где строк по шесть тысяч.
    for group in by_head.values():
        if len(group) < 2:
            continue
        for i, a in enumerate(group):
            for b in group[i + 1:]:
                if a.chain == b.chain and not (a.bkey and b.bkey):
                    continue   # два артикула одной сети с одним названием — не склеиваем
                if union.find(a.id) == union.find(b.id):
                    continue   # уже одна группа: ни сравнение, ни склейка ничего не изменят
                ok, method, score = same_product(a, b, vocab)
                if ok:
                    union.union(a.id, b.id)
                    how.setdefault(a.id, (method, score))
                    how.setdefault(b.id, (method, score))

    groups: dict[int, list[tuple[Row, str, float]]] = defaultdict(list)
    for r in rows:
        method, score = how.get(r.id, ("self", 1.0))
        groups[union.find(r.id)].append((r, method, score))

    out: list[list[tuple[Row, str, float]]] = []
    for group in groups.values():
        out.extend(_split_chained(group, vocab) if len(group) > 2 else [group])
    return out


def _split_chained(group: list[tuple[Row, str, float]], vocab: frozenset[str]
                   ) -> list[list[tuple[Row, str, float]]]:
    """Разбить группу так, чтобы каждый её член совпадал с эталоном НАПРЯМУЮ.

    ЗАЧЕМ. Объединение групп транзитивно, а «тот же товар» — НЕТ. Пара a-b похожа,
    пара b-c похожа, и обе склеиваются через b, хотя a и c — разные вещи. Замер
    20.09.2026 на живом каталоге поймал это в чистом виде: в одной группе оказались
    «Бульон куриный Роллтон Домашний 90 г», «Бульон Роллтон говяжий Домашний 90 г»
    и «Пюре Дары Кубани Яблоко банан клубника 90 г». Ни одна пара из этих трёх не
    прошла бы сравнение сама по себе — их свёл общий сосед.

    Поэтому после объединения группа пересобирается: берём самую подробную строку
    за эталон, оставляем при ней тех, кто совпадает СО ВСЕМИ уже оставленными, а
    остальные уходят собирать свою группу тем же правилом.

    СВЕРЯТЬ ТОЛЬКО С ЭТАЛОНОМ — МАЛО, и это выяснилось замером после первой же
    правки. Молчание уликой не считается: у строки без процента он неизвестен, и
    такая строка пропускает к себе и 15 %, и 20 %. В живом каталоге 20.09.2026
    так и вышло — «Сметана Домик в деревне 300 г» без процента держала при себе
    обе жирности, и 57 групп остались спорными. Проверка со всеми оставленными
    закрывает эту дыру: 15 % и 20 % не проходят друг мимо друга, кто бы ни был
    эталоном.

    Группы из двух строк сюда не попадают: там цепочки быть не может по определению.
    """
    rest = list(group)
    out: list[list[tuple[Row, str, float]]] = []
    while rest:
        seed = max(rest, key=lambda item: (len(item[0].words), len(item[0].name)))
        kept, dropped = [seed], []
        # Признаки группы копятся по мере набора: первая строка, которая НАЗВАЛА
        # процент, задаёт его всей группе. Так закрывается дыра молчащего эталона,
        # и при этом новичок сверяется с одним числом, а не со всеми, кто уже
        # внутри, — иначе честная группа из восьмидесяти одинаковых строк стоила
        # бы трёх тысяч сравнений вместо восьмидесяти.
        pct = seed[0].pct
        marks = seed[0].marks
        # Число штук копится так же: молчащий эталон «Сосиски 300 г» не должен держать
        # при себе и «6 шт 300 г», и «10 шт 300 г».
        packs = seed[0].packs if seed[0].packs > 1 else None
        for item in rest:
            row = item[0]
            if item is seed:
                continue
            if pct is not None and row.pct is not None and not percents_agree(pct, row.pct):
                dropped.append(item)
                continue
            if marks and row.marks and marks != row.marks:
                dropped.append(item)
                continue
            if packs is not None and row.packs > 1 and row.packs != packs:
                dropped.append(item)
                continue
            if not same_product(seed[0], row, vocab)[0]:
                dropped.append(item)
                continue
            kept.append(item)
            if pct is None:
                pct = row.pct
            if not marks:
                marks = row.marks
            if packs is None and row.packs > 1:
                packs = row.packs
        out.append(kept)
        rest = dropped
    return out


def has_cyrillic(text: str | None) -> bool:
    """Есть ли в строке русские буквы."""
    if not text:
        return False
    return any("а" <= ch.lower() <= "я" or ch.lower() == "ё" for ch in text)


def canonical(group: list[tuple[Row, str, float]]) -> dict:
    """Имя и признаки единого товара: самое подробное название, фасовка, марка, штрихкод."""
    rows = [g[0] for g in group]
    # ИМЯ — ПО-РУССКИ, ЕСЛИ ОНО ЕСТЬ (замер 21.10.2026). У молочки владельца каноническим
    # именем стала латинская транслитерация: «moloko ultrapasterizovannoe parmalat pitevoe
    # proteinovoe bezlaktoznoe 18 bez zmzh 1l rossiya». Правило «самое подробное имя»
    # выбрало её, потому что в ней больше слов. А имя единого товара — это и то, что видит
    # человек, и ЗАПРОС в витрины: телефон искал в Магните, Ленте и Пятёрочке латиницей и
    # получал пустую выдачу на всех позициях (живая сборка 21.10: у Магнита и Ленты 0 из 4).
    # Поэтому сначала выбираем среди имён с кириллицей, а латиницу берём, только если
    # русских имён у товара нет вовсе (импорт, латинские марки).
    russian = [r for r in rows if has_cyrillic(r.name)]
    best = max(russian or rows, key=lambda r: (len(r.words), len(r.name)))
    weight = next((r.weight_g for r in rows if r.weight_g), None)
    # марка — как её пишет сеть полем; заглавные из названия — только если поля нет ни у кого
    brand = next((r.brand for r in rows if r.brand), None)
    if not brand:
        caps = next((r.brand_words for r in rows if r.brand_words), None)
        brand = " ".join(sorted(caps)).capitalize() if caps else None
    barcode = next((r.barcode for r in rows if r.barcode), None)
    unit = next((r.unit for r in rows if r.unit), None)
    category = next((r.category for r in rows if r.category), None)
    # norm — слова НАЗВАНИЯ в его порядке (первое слово — обычно сам товар), затем
    # остальные слова группы и марка: поиск сначала смотрит на начало названия
    tail = set().union(*(r.words for r in rows)) - set(best.order)
    # fnorm — все слова группы и марки в общем своде письма, с пробелами по краям:
    # поиск товара человека ищет « основа», то есть начало слова, и находит одной
    # строкой и кириллицу, и латиницу, и полное слово по сокращению чека.
    folded = set().union(*(r.fwords | r.fbrand for r in rows))
    return {"name": best.name, "weight_g": weight, "brand": brand,
            "barcode": barcode, "unit": unit, "category": category,
            "norm": " ".join(best.order + tuple(sorted(tail))),
            "fnorm": f" {' '.join(sorted(folded))} " if folded else None}
