"""Непродуктовые строки чека: услуги, доставка, платежи, аренда, подписки.

ЗАЧЕМ (пункт 2 владельца, 19.10.2026). В чеках не только продукты: такси, перевозка
пассажиров, авансовый платёж, аренда, сборка заказа, подписка. Они попадают в отчёт
привязки как «товары, которых нет в базе», и владелец видит провал там, где искать
было нечего. Из 816 непривязанных товаров боевого рабочего места 80 — услуги и не
продукты (замер 19.10.2026). Этот модуль их узнаёт; врезку в отчёт делает link.py.

ПРАВИЛО, ДВА ШАГА, В ЭТОМ ПОРЯДКЕ:
  1. Товарный признак сильнее маркера услуги: граммовка и объём («200 г», «0,5 л»,
     «10 шт», «19 л»), процент («61 %»), слова «набор», «корм», «средство», «сборная».
     «Сборка» — услуга, «Набор для сборки» — товар, «Сборная солянка» — товар,
     «Доставка воды 19 л» — товар (воду везут, но покупают воду).
  2. Маркер услуги — отдельное слово или начало слова («доставка/доставки/доставкой»,
     «заказ/заказа/заказу») либо фраза («авансовый платёж», «аренда транспортного
     средства»). Отдельно — подписка по сроку: «Light 1месяц», «Месяц … по скидке»,
     «12 месяцев …».

ЛОЖНОЕ СРАБАТЫВАНИЕ ДОРОЖЕ ПРОПУСКА, и это главное свойство модуля. Пропущенная
услуга остаётся в «не найдено» и ничего не ломает; выкинутый из счёта товар владелец не
увидит вовсе. Поэтому словарь узкий, только то, что доказано боевым замером, а любой
товарный признак отменяет вердикт. Лабораторные анализы («Копрограмма», «Тестостерон») и
непродуктовые товары (Myprotein, чехол на Xiaomi) сюда намеренно НЕ входят: это не
услуги, их разбирает другой счётчик.

Модуль только классифицирует: ничего не пишет, никуда не ходит, ничего из приложения
не импортирует (чтобы им могли пользоваться и link.py, и скрипты).
"""
from __future__ import annotations

import re

__all__ = ["is_service_name", "reason"]

# --- шаг 1: товарный признак -------------------------------------------------
# Граммовка и объём — как их пишут чеки: «200Г», «0,5 л», «10 шт», «19л», «2 sht».
_PRODUCT_WEIGHT = re.compile(
    r"\d+(?:[.,]\d+)?\s*(?:г|гр|кг|мг|мл|л|шт|уп|пач|бут|g|gr|kg|mg|ml|l|ltr|sht)"
    r"(?![а-яa-z])")
_PRODUCT_PERCENT = re.compile(r"\d+(?:[.,]\d+)?\s*%")
# Корни товарных слов: «набор» (набор для сборки), «корм» (корм для кошек),
# «средств» (моющее средство), «сборн» (сборная солянка). Сравнение по началу слова:
# «сборн» не путается с «сборк» (сборка), а «средств» ловит и «средство», и «средства».
# ИСКЛЮЧЕНИЕ, проверенное замером 19.10.2026: «транспортное средство» — это машина, а не
# товар. Без него терялись «Аренда транспортного средства», «Продление аренды
# транспортного средства», «Услуга по организации проезда … во время аренды
# транспортного средства» — четыре настоящие услуги из боевых чеков.
_PRODUCT_STEMS = ("набор", "корм", "средств", "сборн")
_VEHICLE = re.compile(r"транспортн\w*\s+средств\w*")

# --- шаг 2: маркеры услуги ---------------------------------------------------
# Фразы — словами в том порядке, как их пишут. Границы слов проверяются, чтобы
# «перевозка» не срабатывала внутри другого слова.
_PHRASES = (
    "перевозка пассажиров",
    "авансовый платеж",
    "вступительный платеж",
    "таможенный платеж",
    "аренда транспортного средства",
    "арендная плата",
    "продление аренды",
    "обработка заказа",
    "сервисный сбор",
    "лицензионное вознаграждение",
    "сборка заказа",
    "плата за подписку",
    "пополнение лицевого счета",
    "предоплата по заказу",
    "стоимость доставки",
    "доставка заказа",
    "доставка товара",
    "курьерская доставка",
    "платная доставка",
    "услуга доставки",
    "подарочная карта",
)
# Начала слов: «доставка/доставки/доставкой», «заказ/заказа/заказу», «платёж/платежа».
# Все они проверены на боевом замере 19.10.2026; ни одно не встречается в названии
# продукта из тех же чеков. «Билет», «бронь», «возврат», «страхование» — поездки,
# мероприятия, гостиницы и страховки: тоже услуги, а не товар.
_WORD_STEMS = ("сборк", "доставк", "перевозк", "авиаперевозк", "аренд", "заказ",
               "платеж", "подписк", "штраф", "пополнен", "чаевые", "комисси", "услуг",
               "тариф", "предоплат", "вознагражден", "аванс", "билет", "бронь", "брони",
               "возврат", "страхован", "страховк")
# Подписка по сроку: «Light 1месяц», «Месяц Lagom PRO по скидке», «12 месяцев …».
_PERIOD = re.compile(r"(?:\d{1,2}\s*)?месяц\w*")
_PERIOD_START = re.compile(r"^(?:\d{1,2}\s*)?месяц\w*")
_TARIFF = ("light", "лайт")
_WORD = re.compile(r"[a-zа-я0-9]+")


def _text(name: str | None) -> str:
    """Название для разбора: нижний регистр, «ё» как «е», одиночные пробелы."""
    return re.sub(r"\s+", " ", str(name or "").lower().replace("ё", "е")).strip()


def _words(text: str) -> list[str]:
    return _WORD.findall(text)


def _product_sign(text: str, words: list[str]) -> str:
    """Товарный признак названия — или пустая строка, если его нет."""
    if _PRODUCT_WEIGHT.search(text):
        return "товарный признак: граммовка или объём"
    if _PRODUCT_PERCENT.search(text):
        return "товарный признак: процент"
    # «Транспортное средство» — машина, а не товарное «средство»: из проверки убираем.
    without_vehicle = _VEHICLE.sub(" ", text)
    for stem in _PRODUCT_STEMS:
        if any(word.startswith(stem) for word in _words(without_vehicle)):
            return f"товарный признак: «{stem}…»"
    return ""


def _phrase(text: str, phrase: str) -> bool:
    """Фраза целиком и отдельными словами."""
    return re.search(rf"(?<![a-zа-я]){re.escape(phrase)}(?![a-zа-я])", text) is not None


def reason(name: str | None) -> str:
    """Почему название — услуга. Пустая строка — это товар (или пустое название).

    Возвращает короткое объяснение для отчёта и тестов: «услуга: «доставка»»,
    «услуга: подписка на срок». Товарный признак отменяет вердикт и тоже назван:
    «товарный признак: граммовка или объём».
    """
    text = _text(name)
    if not text:
        return ""
    words = _words(text)
    product = _product_sign(text, words)
    if product:
        return ""                     # товар сильнее маркера: не услуга
    if _PERIOD_START.match(text) or (any(w in _TARIFF for w in words) and _PERIOD.search(text)):
        return "услуга: подписка на срок"
    for phrase in _PHRASES:
        if _phrase(text, phrase):
            return f"услуга: «{phrase}»"
    for stem in _WORD_STEMS:
        for word in words:
            if word.startswith(stem):
                return f"услуга: «{word}»"
    return ""


def is_service_name(name: str | None) -> bool:
    """Услуга или платёж, а не товар: такую строку не ищем в каталоге сетей."""
    return bool(reason(name))
