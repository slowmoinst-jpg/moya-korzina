"""Товар сети как его видит сборщик, и контракт самого сборщика."""
from __future__ import annotations

import re
import time

from abc import ABC, abstractmethod
from dataclasses import dataclass
from typing import Callable, Iterator


@dataclass
class ChainProduct:
    """Одна строка каталога одной сети. Всё, кроме sku и name, может отсутствовать.

    weight_g — фасовка в граммах или миллилитрах, если сеть её отдаёт числом; если нет,
    сопоставление достанет её из названия само (см. match.py). unit — «pcs» для штучных,
    «kg» для весовых; None — сеть не сказала.
    """
    sku: str
    name: str
    brand: str | None = None
    weight_g: float | None = None
    unit: str | None = None
    category: str | None = None
    url: str | None = None
    image: str | None = None
    barcode: str | None = None
    price: float | None = None
    in_stock: bool | None = None
    # «Товар в каталоге сети есть, подробности не спрашивал». Так сборщик отмечает
    # живыми тысячи уже известных позиций из sitemap, не тратя по запросу на каждую:
    # база продлевает им last_seen, а незнакомые с такой отметкой просто ждут очереди.
    seen_only: bool = False
    # Точка, в которой увидены цена и наличие (storeCode Магнита, код центра METRO).
    # Цена и остаток у сетей свои в каждой точке, и без неё цена второго города
    # затирала цену первого: человек видел чужие цены и чужое наличие.
    point: str | None = None
    # ЦЕНА ВЗЯТА ИЗ НАШЕЙ ЖЕ БАЗЫ, А НЕ УВИДЕНА У СЕТИ. Так бывает, когда витрина закрыта
    # и обход добирает известные товары из базы и чеков. Писать им свежий `price_seen`
    # нельзя: метка значит «сеть назвала цену», а тут её никто не называл. Замер
    # 21.10.2026: частичный обход Пятёрочки освежил метку 93 строкам, и они попали в
    # 6-часовое окно доверия приложения, хотя сеть их сегодня не подтверждала.
    price_from_base: bool = False


Progress = Callable[[str], None]

# Артикулы-заглушки: строка чека (app/connectors/history.PREFIX), строка прайса
# (app/pricelist.SKU_PREFIX), строка справочника data/fallback_prices.csv — она
# пишется как «<код сети>-…» (так сопоставлено демо) — и строка стенда предпросмотра
# «preview-<сеть>-N». Это источники ЦЕНЫ, а не коды товара в сети: по такому
# «артикулу» сеть свой товар не узнает, и класть его в корзину или мостить через него
# единую базу нельзя. Одно правило на всё приложение: наряд, карточка покрытия, дозор
# цен и единая база спрашивают его здесь.
#
# «preview-» заведён 18.10.2026 по отчёту о готовности: стенд предпросмотра заводил
# в store_products строки с именами, буквально равными строкам чеков, и такие строки
# завышали замер сопоставления (48 из 293 на проверочной базе, а связи человека на них
# подтверждались как настоящие). Приставки «preview-» у настоящих артикулов сетей нет.
PLACEHOLDER_PREFIXES = ("hist-", "list-", "preview-")

# Вторая форма строки стенда предпросмотра — «<сеть>-preview-N». Приставкой её не
# поймать: имя начинается с кода сети. Ищем «-preview-» с цифрой следом, без привязки
# к концу строки, чтобы ТО ЖЕ правило выражалось в SQL: регулярных выражений у SQLite
# нет, а GLOB '*‑preview‑[0-9]*' умеет ровно это.
PLACEHOLDER_TAIL = re.compile(r"-preview-[0-9]")


def placeholder_sku(sku: str | None, store_code: str | None = None) -> bool:
    """Заглушка, а не настоящий артикул сети. store_code — узнать и «<сеть>-…».

    ОДИН РЕГИСТР. Сравнение идёт по нижнему и в Python, и в SQL (placeholder_sql):
    LIKE в SQLite регистр ASCII не различает, и правила расходились — «PREVIEW-lenta-7»
    был заглушкой для базы и настоящим артикулом для наряда (adversarial-проверка
    18.10.2026, T11). Теперь правило одно и выражено дважды: здесь и в placeholder_sql.
    """
    text = str(sku or "").lower()
    if text.startswith(PLACEHOLDER_PREFIXES):
        return True
    if PLACEHOLDER_TAIL.search(text):
        return True
    return bool(store_code) and text.startswith(f"{str(store_code).lower()}-")


def placeholder_sql(sku_col: str = "sp.sku", code_col: str = "s.code") -> str:
    """Условие SQL «это заглушка» — то же правило и тот же регистр, что placeholder_sku.

    Отдельной функцией, а не по месту: у правила два выражения, и они уже расходились —
    SQL не знал формы «<сеть>-preview-N», когда строка лежала в чужой сети
    («lenta-preview-7» в магазине Магнита проходила как настоящий артикул). Возвращает
    выражение для WHERE/AND; столбцы задаются алиасами запроса.
    """
    low = f"lower({sku_col})"
    low_code = f"lower({code_col})"
    parts = [f"{low} LIKE '{prefix}%'" for prefix in PLACEHOLDER_PREFIXES]
    parts.append(f"{low} GLOB '*-preview-[0-9]*'")
    parts.append(f"substr({low}, 1, length({low_code}) + 1) = {low_code} || '-'")
    return "(" + " OR ".join(parts) + ")"


class Crawler(ABC):
    """Сборщик каталога одной сети: перечисляет товары, ничего не записывая.

    Правила для всех сборщиков, и они про то, чтобы источник нас пережил: не чаще
    одного запроса в секунду (rate_limit_rps в config.yaml), один поток на сеть,
    пачки и sitemap вместо запроса на каждую карточку. Сборщик каталога читает
    витрину анонимно; вход под учёткой владельца и его корзина живут в его
    браузере (app/shopbrowser, app/collector.py) — это другая дорога к тем же
    данным, а не запрет. Упёрлись в защиту — сборщик поднимает CrawlBlocked с
    объяснением, сеть в этот раз пропускается, а дорогу к ней меняем: браузер
    владельца, его учётка, sitemap, чеки. Остальные сети от этого не страдают.
    """

    code: str = ""
    name: str = ""

    # Обход собрал НЕ весь каталог: раздел не открылся, страница отдалась пустой,
    # часть листьев не обошлась. Признак важен не для журнала, а для базы: пропавшими
    # объявляются только те товары, которых не было в ПОЛНОМ обходе. Без этого признака
    # один сбойный раздел выключал из сопоставления тысячи живых товаров — замер
    # 16.10.2026 у Fix Price: увидено 1 092, а пропавшими помечено 5 400.
    incomplete: bool = False
    incomplete_note: str = ""

    # Сколько товаров в перечне сети и сколько из них ждёт разбора. Сборщик, который
    # перечень получил, выставляет их сам (map_total/map_known/map_left), а обход
    # записывает в store.mark_map: без этих чисел «все товары разобраны» не проверить —
    # 37 тыс. строк Ленты ничего не говорят о том, много это или половина (замер
    # 20.10.2026: в перечне 82 953, осталось 45 617).
    map_total: int | None = None
    map_known: int | None = None
    map_left: int | None = None

    # Когда обход обязан остановиться (time.monotonic), ставит refresh.run_chain по
    # catalog.chain_budget_min. Сборщику это нужно, чтобы ДОБОРНЫЕ проходы (свежесть цен,
    # марка и штрихкод) не съедали остаток потолка: они считают, сколько карточек ещё
    # влезет, и берут столько. Иначе обход упирался в потолок на последнем проходе и
    # записывался НЕПОЛНЫМ, хотя мог спокойно закончиться, просто с меньшим добором.
    deadline: float | None = None

    def cards_left(self, gap: float) -> int | None:
        """Сколько запросов ещё влезет до потолка обхода. None — потолка нет.

        gap — секунды на запрос (Pace.gap). Полсекунды округляются вниз, а не вверх:
        лучше не добрать одну карточку, чем упереться в потолок.
        """
        if self.deadline is None or not gap:
            return None
        return max(0, int((self.deadline - time.monotonic()) / gap))

    @abstractmethod
    def crawl(self, progress: Progress | None = None) -> Iterator[ChainProduct]:
        """Перечислить каталог. Порядок любой; дубли по sku допустимы — база их сложит."""


class CrawlBlocked(Exception):
    """Сеть закрыла дорогу: капча, антибот, 403. Ломиться тем же темпом в ту же дверь
    бессмысленно и только злит источник — фиксируем состояние и меняем маршрут: браузер
    владельца, его учётка, sitemap, MCP, чеки."""
