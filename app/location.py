"""Адрес клиента — то, по чему считаются цены и наличие.

Зачем отдельный модуль. Цена и наличие у сетей свои в каждой точке, поэтому
спрашивать цены «вообще» нельзя — только за конкретного человека по его адресу.
До этого адрес лежал строкой в config.yaml, то есть был настройкой установки,
одной на всех. Здесь он становится ответом пользователя: хранится в базе,
переживает перезапуск и правится с экрана.

Одна ступень для человека. Точку он не выбирает, и в базе она не хранится — хранится
адрес. Точку к адресу подбирает сама Лента: storefront_resolve_store называет хаб
доставки (suggested.delivery), коннектор ходит за ценами по его коду, а ответ лежит
в кэше, так что адрес разрешается один раз (app/connectors/lenta.py, _where()).
Хранить код было бы вредно: сменил адрес — код обязан смениться сам, а сохранённый
пережил бы переезд и молча считал бы цены по старому городу. Выбор точки убрали
15.09.2026 после проверки, которая смотрела на ближайший физический магазин, а не
на хаб доставки: код такого магазина витрина и правда встречает пустотой.

Список ближайших магазинов остался — но как ПРОВЕРКА АДРЕСА, а не как выбор. Если
Лента нашла рядом с ним свои магазины, значит адрес она поняла; если не нашла —
скорее всего опечатка или город не обслуживается, и это надо показать до того, как
человек увидит пустую таблицу цен.

У Магнита ступеней две, и обе здесь. Адресов он не понимает — ему нужен код
магазина, поэтому адрес сначала переводится в точку на карте (app/geo.py, coords),
а по точке спрашивается его справочник магазинов (app/connectors/magnit.py,
nearest_store). Подобранный код и формат точки уходят коннектору как место
клиента. До 16.09.2026 этот код был настройкой установки, одной на всех: человек
из Москвы видел цены Краснодара и заметить этого не мог — чужая цена выглядит
ровно как своя.

Запасной путь сохранён: если адрес в базе не задан или магазин по нему не
подобрался, коннектор берёт значение из config.yaml, как было раньше. Установка
«для себя», где адрес и правда один, продолжает работать без единой правки.
"""
from __future__ import annotations

import logging

from app import repo
from app.models import Location

log = logging.getLogger(__name__)

KEY_ADDRESS = "address"        # адрес клиента, общий для всех сетей
# Когда адрес сменился в последний раз. Снимки цен сетей с ценами по точке, снятые
# раньше, — цены ПРЕЖНЕГО адреса (service.line_price помечает их как несвежие).
KEY_MOVED = "address.changed_at"

# Сети, чьи цены считаются по адресу клиента. Остальные берут своё место из
# config.yaml — то есть показывают всем одну и ту же точку.
#
# Лента разбирает адрес сама: отдаёт хаб доставки, и коннектор уходит его кодом.
# Магнит адресов не понимает вовсе, ему нужен код магазина. Поэтому для него
# ступеней две: адрес переводится в точку на карте (app/geo.py, coords), а по
# точке спрашивается справочник магазинов (app/connectors/magnit.py, nearest_store).
# До 16.09.2026 код магазина Магнита был настройкой установки, одной на всех:
# человек из Москвы видел цены Краснодара и узнать об этом не мог — чужая цена
# выглядит как своя.
#
# METRO добавлен 26.09.2026: ночной обход уже ходил по центру, подобранному к
# адресу, а живые цены и корзина брали connectors.metro_store_id — пустой, то есть
# «точка не задана» и ни одной цены. Центр по адресу подбирает сам коннектор
# (app/connectors/metro.py, _store_id -> nearest_store).
ADDRESS_STORES = ("lenta", "magnit", "metro")


def address() -> str | None:
    """Адрес клиента или None, если он ещё не указан."""
    return repo.get_setting(KEY_ADDRESS)


def save_address(value: str | None) -> bool:
    """Сохранить адрес и поставить его в очередь на загрузку цен. True — адрес сменился.

    Очередь, а не загрузка здесь же, по двум причинам. Подбор точек и обход сетей —
    это минуты сети, и держать на них экран нельзя: человек нажал «Сохранить» и
    должен увидеть результат сразу. И работа эта общая: цены точки одни на всех, кто
    рядом живёт, поэтому делать её должен один фоновый процесс, а не каждый экран.

    Ставим в очередь только настоящую смену адреса. Повторное сохранение того же
    адреса — обычное дело (человек открыл панель и закрыл), и превращать его в
    новый обход незачем; обновление по расписанию всё равно придёт.
    """
    previous = address()
    repo.set_setting(KEY_ADDRESS, value)
    fresh = (value or "").strip()
    if not fresh or fresh == (previous or "").strip():
        return False
    # Отметка смены: цены, снятые по прежнему адресу, остаются в базе, и без неё
    # «Результат» показывал бы их как свежие — чужую точку, а то и чужой город.
    repo.set_setting(KEY_MOVED, repo.NOW())
    try:
        from app.catalog import store as catalog_store
        if catalog_store.enqueue_address(fresh):
            log.info("адрес «%s» поставлен в очередь на загрузку цен", fresh)
    except Exception as exc:  # noqa: BLE001 — очередь не повод не сохранить адрес
        log.warning("адрес «%s» сохранён, но в очередь не встал (%s)", fresh, exc)
    return True


def moved_at() -> str | None:
    """Когда адрес сменился в последний раз. None — не менялся (или не задан)."""
    try:
        return repo.get_setting(KEY_MOVED)
    except Exception:  # noqa: BLE001 — нет базы — нет и отметки
        return None


def nearby(addr: str | None = None) -> list[dict]:
    """Магазины Ленты рядом с адресом — проверка, что адрес вообще понят.

    Пустой список — адрес не разобран или сеть не работает в этом городе. Наружу
    не бросаем: невозможность разобрать адрес — обычное дело, ронять из-за неё
    экран незачем.
    """
    addr = (addr or address() or "").strip()
    if not addr:
        return []
    try:
        from app.connectors.lenta import nearest_stores
        return nearest_stores(addr)
    except Exception as exc:  # noqa: BLE001
        log.warning("адрес «%s» разобрать не удалось (%s)", addr, exc)
        return []


def nearby_magnit(addr: str | None = None) -> list[dict]:
    """Магазины Магнита рядом с адресом — та же проверка адреса, что и у Ленты.

    Пустой список читается так же: адрес не разобран, или в этом городе сети нет.
    Наружу не бросаем по той же причине — экран из-за этого падать не должен.
    """
    addr = (addr or address() or "").strip()
    if not addr:
        return []
    try:
        from app import geo
        from app.connectors.magnit import stores_near
        point = geo.coords(addr)
        return stores_near(*point) if point else []
    except Exception as exc:  # noqa: BLE001
        log.warning("магазины Магнита рядом с «%s» не найдены (%s)", addr, exc)
        return []


def for_store(store_code: str) -> Location | None:
    """Место клиента для этой сети. None — пусть коннектор берёт config.yaml.

    None возвращается в двух случаях: адреса нет вовсе и сеть не умеет считать по
    адресу. Третий случай — сеть умеет, но рядом с адресом её нет — это НЕ None:
    там возвращается место с адресом и без кода точки, и разница принципиальна
    (см. _magnit_place).
    """
    if store_code not in ADDRESS_STORES:
        return None
    addr = address()
    if not addr:
        return None
    if store_code == "magnit":
        return _magnit_place(addr)
    return Location(address=addr)


def _magnit_place(addr: str) -> Location:
    """Ближайший магазин Магнита как место клиента: код и формат точки.

    Возвращается ВСЕГДА место, и в этом весь смысл. Различаются два ответа:

        код есть   — магазин подобран, цены считаются по нему;
        кода нет   — адрес мы знаем, а Магнита рядом с ним нет.

    Второй случай обязан отличаться от «адрес не задан», иначе выходит тихая
    ошибка: коннектор увидел бы пустое место, взял бы запасной магазин из
    config.yaml — краснодарский — и человек в городе без Магнита получил бы
    краснодарские цены с пометкой «живые». Адрес в месте и есть та самая
    отличка: он говорит коннектору «мы знаем, где человек, и здесь тебя нет».

    Найденный код в место кладётся без адреса — по ключу кэша: два адреса с одним
    и тем же ближайшим магазином завели бы две копии одних и тех же цен, и первый
    же переезд по соседней улице заставил бы ходить в сеть за тем, что уже есть.
    """
    try:
        from app.connectors.magnit import nearest_store
        store = nearest_store(addr)
    except Exception as exc:  # noqa: BLE001
        log.warning("магазин Магнита к адресу «%s» не подобран (%s)", addr, exc)
        store = None
    if not store:
        return Location(address=addr)
    from app import config
    # Доставка — если её хотят И если этот магазин её делает. Магазину без доставки
    # цены и корзина доставки ни к чему: кука nmg_dt=DELIVERY уводила окно магазина
    # не туда, и корзина могла не собраться.
    wants = bool(config.get("connectors.magnit_delivery", True))
    return Location(
        store_id=store["code"],
        shop_type=store.get("format") or "ME",
        delivery=wants and bool(store.get("delivery", True)),
    )


def is_set() -> bool:
    return bool(address())
