"""Адрес клиента — то, по чему считаются цены и наличие.

Зачем отдельный модуль. Цена и наличие у сетей свои в каждой точке, поэтому
спрашивать цены «вообще» нельзя — только за конкретного человека по его адресу.
До этого адрес лежал строкой в config.yaml, то есть был настройкой установки,
одной на всех. Здесь он становится ответом пользователя: хранится в базе,
переживает перезапуск и правится с экрана.

Одна ступень, а не две. Поначалу здесь был и выбор ТОЧКИ: адрес разрешался в код
магазина, и дальше запросы шли по коду — он казался однозначнее строки. Проверка
15.09.2026 показала обратное: коды, которые отдаёт Лента по адресу, её же витрина
доставки не принимает — поиск по ним даёт ноль позиций, а карточка цену 0 и
остаток 0, то есть сеть выглядит пустой. Подробности в app/connectors/lenta.py,
_where(). Поэтому точка не хранится и не выбирается: хранится адрес.

Список ближайших магазинов остался — но как ПРОВЕРКА АДРЕСА, а не как выбор. Если
Лента нашла рядом с ним свои магазины, значит адрес она поняла; если не нашла —
скорее всего опечатка или город не обслуживается, и это надо показать до того, как
человек увидит пустую таблицу цен.

Запасной путь сохранён: если адрес в базе не задан, коннектор берёт значение из
config.yaml, как было раньше. Установка «для себя», где адрес и правда один,
продолжает работать без единой правки.
"""
from __future__ import annotations

import logging

from app import repo
from app.models import Location

log = logging.getLogger(__name__)

KEY_ADDRESS = "address"        # адрес клиента, общий для всех сетей

# сети, которые умеют считать по адресу. Остальные берут своё место из config.yaml:
# у Магнита это код магазина в куках, и по адресу он не подбирается.
ADDRESS_STORES = ("lenta",)


def address() -> str | None:
    """Адрес клиента или None, если он ещё не указан."""
    return repo.get_setting(KEY_ADDRESS)


def save_address(value: str | None) -> None:
    repo.set_setting(KEY_ADDRESS, value)


def nearby(addr: str | None = None) -> list[dict]:
    """Магазины Ленты рядом с адресом — проверка, что адрес вообще понят.

    Пустой список — адрес не разобран или сеть не работает в этом городе. Наружу
    не бросаем: невозможность разобрать адрес — обычное дело, ронять из-за неё
    экран незачем.
    """
    addr = (addr or address() or "").strip()
    if not addr:
        return []
    try:
        from app.connectors.lenta import nearest_stores
        return nearest_stores(addr)
    except Exception as exc:  # noqa: BLE001
        log.warning("адрес «%s» разобрать не удалось (%s)", addr, exc)
        return []


def for_store(store_code: str) -> Location | None:
    """Место клиента для этой сети. None — пусть коннектор берёт config.yaml.

    None возвращается намеренно и в двух случаях: адреса нет вовсе, и сеть не умеет
    считать по адресу. Второе важнее: вернуть Магниту место без кода магазина
    значило бы отобрать у него настроенный магазин и молча уехать на магазин сайта
    по умолчанию — в другом городе.
    """
    if store_code not in ADDRESS_STORES:
        return None
    addr = address()
    return Location(address=addr) if addr else None


def is_set() -> bool:
    return bool(address())
