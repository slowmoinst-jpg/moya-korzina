#!/bin/sh
# Вход в контейнер «Моей корзины»: сначала экран, потом приложение.
#
# ЗАЧЕМ ЭКРАН. Окну магазина (app/shopbrowser) нужен обычный Chromium, а не
# headless: headless сообщает странице «за мной никто не смотрит», тогда как за
# ней смотрит человек — она показана ему в экране «Кабинет». Виртуальный экран
# Xvfb и есть то место, где браузер рисует.
#
# ПОЧЕМУ НЕ xvfb-run. Пробовали 17.09.2026 — дважды. Сначала он падал с «xauth
# command not found», потом, уже с xauth, поднял Xvfb и завис на ожидании экрана,
# так и не запустив Python: контейнер стоял «Up», порт молчал, журнал был пуст —
# худший вид поломки, когда всё выглядит живым. Здесь каждый шаг виден в журнале.
#
# ЕСЛИ ЭКРАН НЕ ПОДНЯЛСЯ — приложение всё равно стартует, просто без DISPLAY, и
# браузер сам уходит в headless (app/shopbrowser/driver._headless). Половина
# работы лучше, чем мёртвый контейнер: чеки, расчёт и каталог экрана не просят.
set -u

SCREEN_NUM="${SCREEN_NUM:-99}"

# РАЗМЕР ЭКРАНА ОКНУ КАБИНЕТА НЕ ТЕСЕН, и это проверено, а не предположено.
# Окно кабинета — 820×1000 (app/shopbrowser/driver.WIDTH и HEIGHT), экран 1280×1024.
# Замер 17.09.2026 на живом сервере: снимок приходит полным, 820×1000, и
# window.innerHeight внутри страницы тоже 1000 — низ страницы НЕ обрезан. Это
# важно проверять, а не додумывать: у Магнита кнопка «Войти» стоит в нижней
# панели, и обрезанный низ означал бы «войти некуда».
#
# ЧТО ЗДЕСЬ ДЕЙСТВИТЕЛЬНО ЛОМАЕТСЯ — первый снимок на только что поднятом экране:
# Chromium отвечает «Page.screenshot: Unable to capture screenshot», а следующие
# снимки того же и даже большего размера снимаются подряд без осечки. То есть окно
# ещё не показано, когда мы просим картинку. Лечится повтором в
# app/shopbrowser/driver.shot, а не размером экрана — увеличение до 1440×1440
# первый снимок не спасло.
SCREEN_SIZE="${SCREEN_SIZE:-1280x1024x24}"

start_screen() {
    command -v Xvfb >/dev/null 2>&1 || {
        echo "вход: Xvfb не установлен, работаю без экрана"
        return 1
    }
    rm -f "/tmp/.X${SCREEN_NUM}-lock"
    Xvfb ":${SCREEN_NUM}" -screen 0 "${SCREEN_SIZE}" -nolisten tcp &
    screen_pid=$!

    # Ждём сокет экрана. Пять секунд — с запасом: Xvfb поднимается за десятые доли,
    # а если не поднялся за пять, он не поднимется вовсе.
    waited=0
    while [ "${waited}" -lt 50 ]; do
        if [ -e "/tmp/.X11-unix/X${SCREEN_NUM}" ]; then
            echo "вход: экран :${SCREEN_NUM} поднят (${SCREEN_SIZE}), pid ${screen_pid}"
            return 0
        fi
        kill -0 "${screen_pid}" 2>/dev/null || break
        waited=$((waited + 1))
        sleep 0.1
    done

    echo "вход: экран :${SCREEN_NUM} не поднялся, работаю без него"
    kill "${screen_pid}" 2>/dev/null
    return 1
}

if start_screen; then
    DISPLAY=":${SCREEN_NUM}"
    export DISPLAY
else
    # Именно снять, а не оставить пустым: driver._headless смотрит на наличие
    # переменной, и пустой DISPLAY означал бы «экран есть», которого нет.
    unset DISPLAY
fi

# Команду берём из аргументов, а НЕ вписываем сюда. Из этого же образа поднимается
# второй контейнер — планировщик каталога (`python -m app.catalog.worker`,
# tools/server-deploy.sh). Впиши мы здесь веб-сервер, планировщик молча стал бы
# вторым приложением: контейнер «Up», каталог не обновляется, приёмная дверь молчит.
# exec — чтобы Python стал первым процессом и получал сигналы docker stop сам.
echo "вход: запускаю $*"
exec "$@"
